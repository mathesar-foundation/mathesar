/** Stores a text file as the admin and returns the value of a file cell that holds it. */
async function storeFile(page: Page, name: string): Promise<string> {
  // The upload takes no basic authentication, so it goes through the browser session.
  const { cookies } = await page.context().storageState();
  const csrfToken = cookies.find((cookie) => cookie.name === 'csrftoken');
  const response = await page.request.post('/files/', {
    headers: { 'X-CSRFToken': csrfToken?.value ?? '' },
    multipart: {
      file: { name, mimeType: 'text/plain', buffer: Buffer.from(name) },
    },
  });
  const { result } = (await response.json()) as { result: string };
  return result;
}

/** The "Item" cells of the records on screen, top to bottom. */
export function shownItems(sheet: Sheet): Locator {
  return sheet.cell(sheet.recordRows, 'Item');
}

/** The text of the record count for a result that fits on one page. */
export function showingAll(count: number): string {
  return `Showing 1–${count} of ${count}`;
}

