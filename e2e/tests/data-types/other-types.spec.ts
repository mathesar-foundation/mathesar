import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

test.describe('a cell of a type without its own editor', () => {
  let table: Table;
  let tablePage: TablePage;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Hosts" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Address" inet,
         "Spot" point,
         "Ports" int4range,
         "Config" xml
       );
       INSERT INTO "Hosts" ("Address", "Spot", "Ports", "Config") VALUES
         ('192.168.0.1/24', '(1,2)', '[80,90)', '<port>80</port>');`,
    );
    table = await api.getTable(schema, 'Hosts');
    tablePage = new TablePage(page);
    await tablePage.goto(table);
  });

  test('shows the value as PostgreSQL prints it', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Address')).toHaveText('192.168.0.1/24');
    await expect(sheet.cell(0, 'Spot')).toHaveText('(1,2)');
    await expect(sheet.cell(0, 'Ports')).toHaveText('[80,90)');
    await expect(sheet.cell(0, 'Config')).toHaveText('<port>80</port>');
  });

  test('is edited as text, which the database converts', async () => {
    const { sheet } = tablePage;
    await sheet.editCell(sheet.cell(0, 'Address'), '10.1.2.3');

    await expect(sheet.cell(0, 'Address')).toHaveText('10.1.2.3');
    await expect
      .poll(() => storedValues(table, 'Address'))
      .toEqual(['10.1.2.3/32']);
  });

  test('keeps a value that the type refuses with the error of the database', async () => {
    const { sheet } = tablePage;
    const address = sheet.cell(0, 'Address');
    await sheet.editCell(address, 'nowhere');

    await expect(sheet.errorIndicator(address)).toBeVisible();
    await expect(address).toHaveText('nowhere');
    await expect(sheet.cellErrors).toContainText(
      'invalid input syntax for type inet: "nowhere"',
    );
    expect(await storedValues(table, 'Address')).toEqual(['192.168.0.1/24']);
  });
});
