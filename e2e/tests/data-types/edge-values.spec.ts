import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { pinsKnownBug } from '../../support/known-bugs';
import { TablePage } from '../../support/ui/pages/table-page';

test.describe('values at the edges of their type', () => {
  let table: Table;
  let tablePage: TablePage;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Edges" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Day" date,
         "Stamp" timestamp,
         "Amount" numeric
       );
       INSERT INTO "Edges" ("Day", "Stamp", "Amount") VALUES
         ('0044-03-15 BC', '0001-01-01 00:00', 'NaN'),
         ('infinity', '-infinity', 'Infinity'),
         ('9999-12-31', '9999-12-31 23:59', 0);`,
    );
    table = await api.getTable(schema, 'Edges');
    tablePage = new TablePage(page);
    await tablePage.goto(table);
  });

  test('the last minute of the year 9999 is shown as such', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(2, 'Day')).toHaveText('12/31/9999');
    await expect(sheet.cell(2, 'Stamp')).toHaveText('12/31/9999 23:59');
  });

  test(
    'dates before the year 100 are shown in the 20th century, without BC',
    pinsKnownBug('early-dates-shown-in-the-20th-century'),
    async () => {
      const { sheet } = tablePage;
      await expect(sheet.cell(0, 'Day')).toHaveText('03/15/1944');
      await expect(sheet.cell(0, 'Stamp')).toHaveText('01/01/1901 00:00');
    },
  );

  test.fixme('dates before the year 100 are shown with their year and era', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Day')).toHaveText(/0044.*BC/);
    await expect(sheet.cell(0, 'Stamp')).toHaveText('01/01/0001 00:00');
  });

  test(
    'infinite dates are shown as NULL or as a colon',
    pinsKnownBug('infinite-dates-shown-wrong'),
    async () => {
      const { sheet } = tablePage;
      await expect(sheet.cell(1, 'Day')).toHaveText('NULL');
      await expect(sheet.cell(1, 'Stamp')).toHaveText(':');
    },
  );

  test.fixme('infinite dates are shown as infinity', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(1, 'Day')).toHaveText('infinity');
    await expect(sheet.cell(1, 'Stamp')).toHaveText('-infinity');
  });

  test(
    'NaN and Infinity are shown as empty cells',
    pinsKnownBug('special-numbers-shown-empty'),
    async () => {
      const { sheet } = tablePage;
      await expect(sheet.cell(2, 'Amount')).toHaveText('0');
      await expect(sheet.cell(0, 'Amount')).toHaveText('');
      await expect(sheet.cell(1, 'Amount')).toHaveText('');
    },
  );

  test.fixme('NaN and Infinity are shown as such', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Amount')).toHaveText('NaN');
    await expect(sheet.cell(1, 'Amount')).toHaveText('Infinity');
  });
});
