import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { pinsKnownBug } from '../../support/known-bugs';
import { recordRpcCalls } from '../../support/rpc-log';
import { DateTimePicker } from '../../support/ui/components/date-time-picker';
import {
  dropdownOffset,
  focusIsOnPage,
} from '../../support/ui/components/typed-cells';
import { openSelect } from '../../support/ui/components/select';
import { expectStaysOpen } from '../../support/ui/components/transitions';
import { ColumnFormatting } from '../../support/ui/pages/column-formatting';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

test.describe('a date cell', () => {
  let table: Table;
  let tablePage: TablePage;
  let picker: DateTimePicker;

  test.beforeEach(async ({ page, api, schema }) => {
    await page.clock.setFixedTime(new Date('2024-05-20T10:30:00Z'));
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Events" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Day" date,
         "Note" text
       );
       INSERT INTO "Events" ("Day", "Note") VALUES
         ('2024-03-15', 'launch'), (NULL, 'unplanned');`,
    );
    table = await api.getTable(schema, 'Events');
    tablePage = new TablePage(page);
    picker = new DateTimePicker(page);
    await tablePage.goto(table);
  });

  test('shows the date in the format of the browser language, and NULL', async () => {
    await expect(tablePage.sheet.cell(0, 'Day')).toHaveText('03/15/2024');
    await expect(tablePage.sheet.cell(1, 'Day')).toHaveText('NULL');
  });

  test('Enter opens the date and a calendar of its month, which stay open while typing', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').click();
    await page.keyboard.press('Enter');

    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('03/15/2024');
    await expect(sheet.editor).toHaveAttribute('placeholder', 'MM/DD/YYYY');
    await expect(picker.month).toHaveText('March');
    await expect(picker.year).toHaveValue('2024');
    await expect(picker.selectedDay).toHaveText('15');

    await page.keyboard.press('Backspace');
    await page.keyboard.type('3');
    await expect(sheet.editor).toHaveValue('03/15/2023');
    await expect(picker.year).toHaveValue('2023');
  });

  test('a double click opens the date and the calendar, which stay open while typing', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').dblclick();

    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('03/15/2024');
    await expect(picker.selectedDay).toHaveText('15');

    await page.keyboard.press('End');
    await page.keyboard.press('Backspace');
    await page.keyboard.type('3');
    await expect(sheet.editor).toHaveValue('03/15/2023');
    await expect(picker.year).toHaveValue('2023');
  });

  test('the calendar opens under the input', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').click();
    await page.keyboard.press('Enter');

    await expect
      .poll(() => dropdownOffset(picker.root, sheet.editor))
      .toEqual({ x: expect.closeTo(0, -1), y: expect.closeTo(0, -1) });
  });

  test('a NULL date opens an empty input and the calendar of the current month', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Day').click();
    await page.keyboard.press('Enter');

    await expect(sheet.editor).toHaveValue('');
    await expect(picker.month).toHaveText('May');
    await expect(picker.year).toHaveValue('2024');
    await expect(picker.selectedDay).toHaveCount(0);
  });

  test('a typed date moves the calendar to it, and Enter stores it', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('12/25/2023');

    await expect(picker.month).toHaveText('December');
    await expect(picker.year).toHaveValue('2023');
    await expect(picker.selectedDay).toHaveText('25');

    await page.keyboard.press('Enter');
    await expect(sheet.editor).toHaveCount(0);
    await expect(picker.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Day')).toHaveText('12/25/2023');
    await sheet.expectFocusOnActiveCell();
    await expect
      .poll(() => storedValues(table, 'Day'))
      .toEqual(['2023-12-25', null]);
  });

  test('a day picked in the calendar is stored and closes the editor', async () => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').dblclick();
    await picker.day(20).click();

    await expect(sheet.editor).toHaveCount(0);
    await expect(picker.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Day')).toHaveText('03/20/2024');
    await expect
      .poll(() => storedValues(table, 'Day'))
      .toEqual(['2024-03-20', null]);
  });

  test('the cell does not get the keyboard focus back after a day was picked', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').dblclick();
    await picker.day(20).click();
    await expect(sheet.cell(0, 'Day')).toHaveText('03/20/2024');

    await expect.poll(() => focusIsOnPage(page)).toBe(true);
    await expect(sheet.focusTarget(sheet.activeCell)).not.toBeFocused();
  });

  test('the arrow to the next month keeps the editor open', async () => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').dblclick();
    await picker.nextMonthButton.click();

    await expectStaysOpen(picker.root);
    await expect(picker.month).toHaveText('April');
    await expect(sheet.editor).toHaveValue('03/15/2024');

    await picker.day(7).click();
    await expect(sheet.cell(0, 'Day')).toHaveText('04/07/2024');
    await expect
      .poll(() => storedValues(table, 'Day'))
      .toEqual(['2024-04-07', null]);
  });

  test('a click into the input takes the focus from the calendar and keeps the editor open', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').dblclick();
    await picker.nextMonthButton.click();
    await expect(sheet.editor).not.toBeFocused();
    await sheet.editor.click();
    await page.keyboard.press('End');
    await page.keyboard.press('Backspace');
    await page.keyboard.type('3');

    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('03/15/2023');
    await expect(picker.year).toHaveValue('2023');
  });

  test('Escape and Enter leave the editor open while the calendar has the focus', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').dblclick();
    await picker.nextMonthButton.click();
    await expect(sheet.editor).not.toBeFocused();
    await page.keyboard.press('Escape');
    await page.keyboard.press('Enter');

    await expectStaysOpen(picker.root);
    await expect(sheet.editor).toHaveValue('03/15/2024');
    await expect(picker.month).toHaveText('April');
  });

  test('Today and Yesterday set the date relative to the current day', async () => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').dblclick();
    await expect(picker.preset('Today')).toContainText('05/20/2024');
    await picker.preset('Today').click();
    await expect(sheet.cell(0, 'Day')).toHaveText('05/20/2024');

    await sheet.cell(1, 'Day').dblclick();
    await expect(picker.preset('Yesterday')).toContainText('05/19/2024');
    await picker.preset('Yesterday').click();
    await expect(sheet.cell(1, 'Day')).toHaveText('05/19/2024');

    await expect
      .poll(() => storedValues(table, 'Day'))
      .toEqual(['2024-05-20', '2024-05-19']);
  });

  test('Escape closes the editor and discards the typed date', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    const rpcCalls = recordRpcCalls(page);
    await sheet.cell(0, 'Day').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('01/01/2000');
    await expect(sheet.editor).toHaveValue('01/01/2000');
    await page.keyboard.press('Escape');

    await expect(sheet.editor).toHaveCount(0);
    await expect(picker.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Day')).toHaveText('03/15/2024');
    await sheet.expectFocusOnActiveCell();
    expect(rpcCalls).not.toContain('records.patch');
    expect(await storedValues(table, 'Day')).toEqual(['2024-03-15', null]);
  });

  test('Tab stores the typed date and moves to the next cell', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('01/02/2020');
    await page.keyboard.press('Tab');

    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.activeCell).toHaveText('launch');
    await sheet.expectFocusOnActiveCell();
    await expect
      .poll(() => storedValues(table, 'Day'))
      .toEqual(['2020-01-02', null]);
  });

  test('a click on another cell stores the typed date and closes the calendar', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('01/02/2020');
    await sheet.cell(0, 'Note').click();

    await expect(sheet.editor).toHaveCount(0);
    await expect(picker.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Day')).toHaveText('01/02/2020');
    await expect(sheet.activeCell).toHaveText('launch');
    await expect
      .poll(() => storedValues(table, 'Day'))
      .toEqual(['2020-01-02', null]);
  });

  test('an emptied input stores NULL', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Day').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Control+A');
    await page.keyboard.press('Backspace');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(0, 'Day')).toHaveText('NULL');
    await expect.poll(() => storedValues(table, 'Day')).toEqual([null, null]);
  });

  test('a text that is no date stays in the cell with the database error', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    const day = sheet.cell(0, 'Day');
    await day.click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('soon');
    await page.keyboard.press('Enter');

    await expect(sheet.errorIndicator(day)).toBeVisible();
    await expect(day).toHaveText('soon');
    await expect(sheet.cellErrors).toContainText(
      'invalid input syntax for type date: "soon"',
    );
    expect(await storedValues(table, 'Day')).toEqual(['2024-03-15', null]);
  });

  test(
    'names every day of the calendar with a broken date format',
    pinsKnownBug('date-picker-day-names'),
    async () => {
      await tablePage.sheet.cell(0, 'Day').dblclick();

      await expect(picker.day(15)).toHaveAccessibleName('F j, +0000');
    },
  );

  test.fixme('names every day of the calendar with its date', async () => {
    await tablePage.sheet.cell(0, 'Day').dblclick();

    await expect(picker.day(15)).toHaveAccessibleName('March 15, 2024');
  });

  test(
    'stores the 30th of February as the 2nd of March',
    pinsKnownBug('date-input-rolls-over-invalid-days'),
    async ({ page }) => {
      const { sheet } = tablePage;
      await sheet.cell(0, 'Day').click();
      await page.keyboard.press('Enter');
      await page.keyboard.press('Control+A');
      await page.keyboard.type('02/30/2023');
      await page.keyboard.press('Enter');

      await expect(sheet.cell(0, 'Day')).toHaveText('03/02/2023');
      await expect
        .poll(() => storedValues(table, 'Day'))
        .toEqual(['2023-03-02', null]);
    },
  );

  test.fixme('refuses the 30th of February', async ({ page }) => {
    const { sheet } = tablePage;
    const day = sheet.cell(0, 'Day');
    await day.click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('02/30/2023');
    await page.keyboard.press('Enter');

    await expect(sheet.errorIndicator(day)).toBeVisible();
    expect(await storedValues(table, 'Day')).toEqual(['2024-03-15', null]);
  });
});

test.describe('the date format of a column', () => {
  let table: Table;
  let tablePage: TablePage;
  let formatting: ColumnFormatting;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Events" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Day" date
       );
       INSERT INTO "Events" ("Day") VALUES ('2024-03-15'), (NULL);`,
    );
    table = await api.getTable(schema, 'Events');
    tablePage = new TablePage(page);
    formatting = new ColumnFormatting(tablePage.inspector);
    await tablePage.goto(table);
    await tablePage.sheet.columnHeader('Day').click();
  });

  test('offers five formats, each shown with an example', async () => {
    await expect(formatting.select('Date Format')).toHaveText(
      'Infer from browser (12/31/2001)',
    );
    const options = await openSelect(formatting.select('Date Format'));

    await expect(options.getByRole('option')).toHaveText([
      'Infer from browser (12/31/2001)',
      'US (12/31/2001)',
      'European (31/12/2001)',
      'Friendly (31 Dec 2001)',
      'Standard (2001-12-31)',
    ]);
  });

  test('changes the cells and the input once saved', async ({ page, api }) => {
    const { sheet } = tablePage;
    await formatting.choose('Date Format', /^Friendly/);
    await formatting.saveButton.click();

    await expect(formatting.saveButton).toHaveCount(0);
    await expect(sheet.cell(0, 'Day')).toHaveText('15 Mar 2024');
    await expect(sheet.cell(1, 'Day')).toHaveText('NULL');
    await expect
      .poll(() => api.columnMetadata(table, 'Day'))
      .toEqual({ date_format: 'friendly' });

    await sheet.cell(0, 'Day').click();
    await page.keyboard.press('Enter');
    await expect(sheet.editor).toHaveValue('15 Mar 2024');
    await expect(sheet.editor).toHaveAttribute('placeholder', 'D MMM YYYY');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('1 Jan 2020');
    await page.keyboard.press('Enter');
    await expect
      .poll(() => storedValues(table, 'Day'))
      .toEqual(['2020-01-01', null]);
  });
});
