import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { arrayItems } from '../../support/ui/components/typed-cells';
import { TablePage } from '../../support/ui/pages/table-page';

test.describe('an array cell', () => {
  let table: Table;
  let tablePage: TablePage;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Posts" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Tags" text[],
         "Scores" integer[]
       );
       INSERT INTO "Posts" ("Tags", "Scores") VALUES
         ('{x,"y z",NULL}', '{1234,5}'), ('{}', NULL);`,
    );
    table = await api.getTable(schema, 'Posts');
    tablePage = new TablePage(page);
    await tablePage.goto(table);
  });

  test('shows each item, NULL items as such and an empty array as nothing', async () => {
    const { sheet } = tablePage;
    await expect(arrayItems(sheet.cell(0, 'Tags'))).toHaveText([
      'x',
      'y z',
      'NULL',
    ]);
    await expect(arrayItems(sheet.cell(1, 'Tags'))).toHaveCount(0);
    await expect(sheet.cell(1, 'Tags')).toHaveText('');
    await expect(sheet.cell(1, 'Scores')).toHaveText('NULL');
  });

  test('formats number items as numbers', async () => {
    await expect(arrayItems(tablePage.sheet.cell(0, 'Scores'))).toHaveText([
      '1,234',
      '5',
    ]);
  });

  test('opens no editor on Enter or a double click', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Tags').click();
    await page.keyboard.press('Enter');
    await expect(sheet.editor).toHaveCount(0);
    await sheet.expectFocusOnActiveCell();

    await sheet.cell(0, 'Tags').dblclick();
    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.cell(0, 'Tags')).toHaveAttribute('data-cell-active');
    await sheet.expectFocusOnActiveCell();
  });
});
