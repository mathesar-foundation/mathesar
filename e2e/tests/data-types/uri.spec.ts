import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { uriLink } from '../../support/ui/components/typed-cells';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

test.describe('a URI cell', () => {
  let table: Table;
  let tablePage: TablePage;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Sites" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Address" mathesar_types.uri
       );
       INSERT INTO "Sites" ("Address") VALUES
         ('https://mathesar.org/docs?page=1'), ('mailto:team@example.com');`,
    );
    table = await api.getTable(schema, 'Sites');
    tablePage = new TablePage(page);
    await tablePage.goto(table);
  });

  test('links a web address to a new tab only while the cell is active', async () => {
    const { sheet } = tablePage;
    const address = sheet.cell(0, 'Address');
    await expect(address).toHaveText('https://mathesar.org/docs?page=1');
    await expect(uriLink(address)).toHaveCount(0);

    await address.click();
    await expect(uriLink(address)).toHaveAttribute(
      'href',
      'https://mathesar.org/docs?page=1',
    );
    await expect(uriLink(address)).toHaveAttribute('target', '_blank');
  });

  test('does not link an address of another scheme', async () => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Address').click();

    await expect(sheet.cell(1, 'Address')).toHaveAttribute('data-cell-active');
    await expect(sheet.cell(1, 'Address')).toHaveText(
      'mailto:team@example.com',
    );
    await expect(uriLink(sheet.cell(1, 'Address'))).toHaveCount(0);
  });

  test('a click on another cell stores the typed address', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Address').click();
    await page.keyboard.press('Enter');
    await sheet.editor.fill('https://example.org');
    await sheet.cell(0, 'Address').click();

    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.cell(1, 'Address')).toHaveText('https://example.org');
    await expect
      .poll(() => storedValues(table, 'Address'))
      .toEqual(['https://mathesar.org/docs?page=1', 'https://example.org']);
  });

  test('keeps a text that is no URI with the error of the database', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    const address = sheet.cell(0, 'Address');
    await address.click();
    await page.keyboard.press('Enter');
    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('https://mathesar.org/docs?page=1');
    await sheet.editor.fill('no address');
    await page.keyboard.press('Enter');

    await expect(sheet.errorIndicator(address)).toBeVisible();
    await expect(address).toHaveText('no address');
    await expect(sheet.cellErrors).toContainText(
      'value for domain mathesar_types.uri violates check constraint "uri_check"',
    );
    expect(await storedValues(table, 'Address')).toEqual([
      'https://mathesar.org/docs?page=1',
      'mailto:team@example.com',
    ]);
  });
});
