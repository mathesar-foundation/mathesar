import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { pinsKnownBug } from '../../support/known-bugs';
import { recordRpcCalls } from '../../support/rpc-log';
import { ColumnFormatting } from '../../support/ui/pages/column-formatting';
import { TablePage } from '../../support/ui/pages/table-page';

let table: Table;
let tablePage: TablePage;
let formatting: ColumnFormatting;

test.beforeEach(async ({ page, api, schema }) => {
  await runSqlInSchema(
    schema,
    `CREATE TYPE "Level" AS ENUM ('low', 'high');
     CREATE TABLE "Events" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Day" date,
       "Due" date,
       "Name" text,
       "Contact" mathesar_types.email,
       "Code" uuid,
       "Data" jsonb,
       "Tags" text[],
       "Level" "Level",
       "Parent" integer REFERENCES "Events" (id)
     );
     INSERT INTO "Events" ("Day") VALUES ('2024-03-15');`,
  );
  table = await api.getTable(schema, 'Events');
  tablePage = new TablePage(page);
  formatting = new ColumnFormatting(tablePage.inspector);
  await tablePage.goto(table);
});

test.describe('the Formatting section of the inspector', () => {
  test('shows Cancel and Save once it is clicked', async () => {
    await tablePage.sheet.columnHeader('Day').click();
    await expect(formatting.select('Date Format')).toBeVisible();
    await expect(formatting.saveButton).toHaveCount(0);

    await formatting.choose('Date Format', /^Friendly/);
    await expect(formatting.cancelButton).toBeVisible();
    await expect(formatting.saveButton).toBeEnabled();
  });

  test('Cancel restores the stored options without a request', async ({
    page,
    api,
  }) => {
    const { sheet } = tablePage;
    await sheet.columnHeader('Day').click();
    const rpcCalls = recordRpcCalls(page);
    await formatting.choose('Date Format', /^Friendly/);
    await expect(formatting.select('Date Format')).toHaveText(
      'Friendly (31 Dec 2001)',
    );
    await formatting.cancelButton.click();

    await expect(formatting.select('Date Format')).toHaveText(
      'Infer from browser (12/31/2001)',
    );
    await expect(formatting.saveButton).toHaveCount(0);
    await expect(sheet.cell(0, 'Day')).toHaveText('03/15/2024');
    expect(rpcCalls).toEqual([]);
    expect(await api.columnMetadata(table, 'Day')).toEqual({});
  });

  test('drops an option that was not saved when another column is selected', async ({
    api,
  }) => {
    const { sheet } = tablePage;
    await sheet.columnHeader('Day').click();
    await formatting.choose('Date Format', /^Standard/);
    await expect(formatting.select('Date Format')).toHaveText(
      'Standard (2001-12-31)',
    );
    await sheet.columnHeader('Due').click();

    await expect(formatting.select('Date Format')).toHaveText(
      'Infer from browser (12/31/2001)',
    );
    await expect(formatting.saveButton).toHaveCount(0);

    await sheet.columnHeader('Day').click();
    await expect(formatting.select('Date Format')).toHaveText(
      'Infer from browser (12/31/2001)',
    );
    await expect(sheet.cell(0, 'Day')).toHaveText('03/15/2024');
    expect(await api.columnMetadata(table, 'Day')).toEqual({});
  });

  test('a saved option is still in effect after a reload', async () => {
    const { sheet } = tablePage;
    await sheet.columnHeader('Day').click();
    await formatting.choose('Date Format', /^Standard/);
    await formatting.saveButton.click();
    await expect(sheet.cell(0, 'Day')).toHaveText('2024-03-15');

    await tablePage.goto(table);
    await expect(sheet.cell(0, 'Day')).toHaveText('2024-03-15');
    await sheet.columnHeader('Day').click();
    await expect(formatting.select('Date Format')).toHaveText(
      'Standard (2001-12-31)',
    );
  });

  test('says so for columns without options', async () => {
    const { sheet } = tablePage;
    for (const column of [
      'Name',
      'id',
      'Contact',
      'Code',
      'Data',
      'Tags',
      'Level',
      'Parent',
    ]) {
      await sheet.columnHeader('Day').click();
      await expect(formatting.noOptionsNote).toHaveCount(0);
      await sheet.columnHeader(column).click();
      await expect(formatting.noOptionsNote, column).toBeVisible();
    }
  });

  test(
    'shows no Save button for an option chosen with the keyboard',
    pinsKnownBug('formatting-save-needs-a-click'),
    async ({ page }) => {
      await tablePage.sheet.columnHeader('Day').click();
      await formatting.select('Date Format').focus();
      await page.keyboard.press('Enter');
      await page.keyboard.press('ArrowDown');
      await page.keyboard.press('Enter');

      await expect(formatting.select('Date Format')).toHaveText(
        'US (12/31/2001)',
      );
      await expect(formatting.saveButton).toHaveCount(0);
    },
  );

  test.fixme('saves an option chosen with the keyboard', async ({
    page,
    api,
  }) => {
    await tablePage.sheet.columnHeader('Day').click();
    await formatting.select('Date Format').focus();
    await page.keyboard.press('Enter');
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Enter');
    await formatting.saveButton.click();

    await expect
      .poll(() => api.columnMetadata(table, 'Day'))
      .toEqual({ date_format: 'us' });
  });

  test(
    'after a save, the first click on a select only shows the buttons',
    pinsKnownBug('formatting-select-ignores-first-click'),
    async ({ browserName }) => {
      test.skip(
        browserName !== 'chromium',
        'The bug does not happen in Firefox and WebKit',
      );
      const { sheet } = tablePage;
      await sheet.columnHeader('Day').click();
      await formatting.choose('Date Format', /^Friendly/);
      await formatting.saveButton.click();
      await expect(formatting.saveButton).toHaveCount(0);

      await formatting.select('Date Format').click();
      await expect(formatting.saveButton).toBeVisible();
      await expect(formatting.openOptions).toHaveCount(0);

      await formatting.select('Date Format').click();
      await expect(formatting.openOptions).toBeVisible();
    },
  );

  test.fixme('after a save, a click opens a select', async () => {
    const { sheet } = tablePage;
    await sheet.columnHeader('Day').click();
    await formatting.choose('Date Format', /^Friendly/);
    await formatting.saveButton.click();
    await expect(formatting.saveButton).toHaveCount(0);

    await formatting.select('Date Format').click();
    await expect(formatting.openOptions).toBeVisible();
  });
});
