import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { pinsKnownBug } from '../../support/known-bugs';
import { fillFormattedInput } from '../../support/ui/components/formatted-input';
import { caretPosition } from '../../support/ui/components/typed-cells';
import { ColumnFormatting } from '../../support/ui/pages/column-formatting';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

let table: Table;
let tablePage: TablePage;

test.beforeEach(async ({ page, api, schema }) => {
  await runSqlInSchema(
    schema,
    `CREATE TABLE "Accounts" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Balance" mathesar_types.mathesar_money,
       "Legacy" money
     );
     INSERT INTO "Accounts" ("Balance", "Legacy") VALUES
       (1234.5, 1234.5), (-5, -5), (NULL, NULL);`,
  );
  table = await api.getTable(schema, 'Accounts');
  tablePage = new TablePage(page);
});

test.describe('a money cell', () => {
  test.beforeEach(async () => {
    await tablePage.goto(table);
  });

  test('shows the amount aligned right with a dollar sign after the minus, also for the PostgreSQL money type', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Balance')).toHaveText('$1,234.5');
    await expect(sheet.cell(1, 'Balance')).toHaveText('-$5');
    await expect(sheet.cell(2, 'Balance')).toHaveText('NULL');
    await expect(sheet.cell(0, 'Legacy')).toHaveText('$1,234.5');
    await expect(sheet.cell(1, 'Legacy')).toHaveText('-$5');
    await expect(sheet.focusTarget(sheet.cell(0, 'Balance'))).toHaveCSS(
      'text-align',
      'right',
    );
  });

  test('Enter opens the amount without its currency sign, which typing also leaves out', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Balance').click();
    await page.keyboard.press('Enter');
    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('1,234.5');

    await page.keyboard.press('Control+A');
    await page.keyboard.type('$-2500.129');
    await expect(sheet.editor).toHaveValue('-2,500.129');
    await expect.poll(() => caretPosition(sheet.editor)).toBe(10);
    await page.keyboard.press('Enter');

    await expect(sheet.cell(0, 'Balance')).toHaveText('-$2,500.129');
    await expect
      .poll(() => storedValues(table, 'Balance'))
      .toEqual(['-2500.129', '-5', null]);
  });

  test('a click on another cell stores the typed amount', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.cell(2, 'Balance').click();
    await page.keyboard.press('Enter');
    await page.keyboard.type('12.5');
    await sheet.cell(0, 'Legacy').click();

    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.cell(2, 'Balance')).toHaveText('$12.5');
    await expect
      .poll(() => storedValues(table, 'Balance'))
      .toEqual(['1234.5', '-5', '12.5']);
  });

  test('an amount typed into a PostgreSQL money column is stored', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(2, 'Legacy').click();
    await page.keyboard.press('Enter');
    await page.keyboard.type('12.5');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(2, 'Legacy')).toHaveText('$12.5');
    await expect
      .poll(() => storedValues(table, 'Legacy'))
      .toEqual(['$1,234.50', '-$5.00', '$12.50']);
  });

  test('the currency symbol, its place and the decimal places change the cells once saved', async ({
    api,
  }) => {
    const { sheet } = tablePage;
    const formatting = new ColumnFormatting(tablePage.inspector);
    await sheet.columnHeader('Balance').click();
    await formatting.field('Currency Symbol').fill('€');
    await formatting.choose('Currency Symbol Location', 'End');
    await fillFormattedInput(formatting.field('Decimal Places'), '2');
    await formatting.saveButton.click();

    await expect(sheet.cell(0, 'Balance')).toHaveText('1,234.50 €');
    await expect(sheet.cell(1, 'Balance')).toHaveText('-5.00 €');
    await expect
      .poll(() => api.columnMetadata(table, 'Balance'))
      .toEqual({
        mon_currency_symbol: '€',
        mon_currency_location: 'end-with-space',
        num_min_frac_digits: 2,
        num_max_frac_digits: 2,
        num_grouping: 'auto',
      });
  });
});

test.describe('a multicurrency money cell', () => {
  test.beforeEach(async () => {
    await runSqlInSchema(
      table.schema,
      `ALTER TABLE "Accounts" ADD COLUMN "Foreign" mathesar_types.multicurrency_money;
       UPDATE "Accounts" SET "Foreign" = ROW(12.5, 'EUR') WHERE id = 1;`,
    );
    await tablePage.goto(table);
  });

  test(
    'shows a dollar sign only',
    pinsKnownBug('multicurrency-money-shown-as-dollar-sign'),
    async () => {
      await expect(tablePage.sheet.cell(0, 'Foreign')).toHaveText('$');
    },
  );

  test.fixme('shows the amount and its currency', async () => {
    const foreign = tablePage.sheet.cell(0, 'Foreign');
    await expect(foreign).toContainText('12.5');
    await expect(foreign).toContainText('EUR');
  });
});

test.describe('a money cell that shows no decimal places', () => {
  test.beforeEach(async ({ api }) => {
    await api.setColumnMetadata(table, 'Balance', {
      num_min_frac_digits: 0,
      num_max_frac_digits: 0,
    });
    await tablePage.goto(table);
  });

  test(
    'opens the rounded amount, and an edit stores it rounded',
    pinsKnownBug('number-editor-rounds-to-decimal-places'),
    async ({ page }) => {
      const { sheet } = tablePage;
      await expect(sheet.cell(0, 'Balance')).toHaveText('$1,235');
      await sheet.cell(0, 'Balance').click();
      await page.keyboard.press('Enter');
      await expect(sheet.editor).toHaveValue('1,235');
      await page.keyboard.press('Home');
      await page.keyboard.type('1');
      await page.keyboard.press('Enter');

      await expect
        .poll(() => storedValues(table, 'Balance'))
        .toEqual(['11235', '-5', null]);
    },
  );

  test.fixme('opens the whole amount, and an edit keeps its decimals', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Balance').click();
    await page.keyboard.press('Enter');
    await expect(sheet.editor).toHaveValue('1,234.5');
    await page.keyboard.press('Home');
    await page.keyboard.type('1');
    await page.keyboard.press('Enter');

    await expect
      .poll(() => storedValues(table, 'Balance'))
      .toEqual(['11234.5', '-5', null]);
  });
});
