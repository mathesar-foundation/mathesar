import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { pinsKnownBug } from '../../support/known-bugs';
import { DateTimePicker } from '../../support/ui/components/date-time-picker';
import { ColumnFormatting } from '../../support/ui/pages/column-formatting';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

test.describe('a date and time cell', () => {
  let table: Table;
  let tablePage: TablePage;
  let picker: DateTimePicker;

  test.beforeEach(async ({ page, api, schema }) => {
    await page.clock.setFixedTime(new Date('2024-05-20T10:30:00Z'));
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Visits" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Arrived" timestamp,
         "Zoned" timestamp with time zone
       );
       INSERT INTO "Visits" ("Arrived", "Zoned") VALUES
         ('2024-03-15 13:45:10', '2024-03-15 13:45:10+02'), (NULL, NULL);`,
    );
    table = await api.getTable(schema, 'Visits');
    tablePage = new TablePage(page);
    picker = new DateTimePicker(page);
    await tablePage.goto(table);
  });

  test('shows date, hours and minutes, with a time zone converted to that of the browser', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Arrived')).toHaveText('03/15/2024 13:45');
    await expect(sheet.cell(0, 'Zoned')).toHaveText('03/15/2024 11:45');
    await expect(sheet.cell(1, 'Arrived')).toHaveText('NULL');
  });

  test('Enter opens the value, a calendar and the time fields, which stay open while typing', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Arrived').click();
    await page.keyboard.press('Enter');

    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('03/15/2024 13:45');
    await expect(sheet.editor).toHaveAttribute(
      'placeholder',
      'MM/DD/YYYY HH:mm',
    );
    await expect(picker.month).toHaveText('March');
    await expect(picker.selectedDay).toHaveText('15');
    await expect(picker.hour).toHaveValue('13');
    await expect(picker.minute).toHaveValue('45');

    await page.keyboard.press('Control+A');
    await page.keyboard.type('1/2/2020 9:05');
    await expect(picker.month).toHaveText('January');
    await expect(picker.year).toHaveValue('2020');
    await expect(picker.selectedDay).toHaveText('2');
    await expect(picker.hour).toHaveValue('09');
  });

  test('a double click opens the value, the calendar and the time fields, which stay open while typing', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Arrived').dblclick();

    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('03/15/2024 13:45');
    await expect(picker.selectedDay).toHaveText('15');
    await expect(picker.hour).toHaveValue('13');

    await page.keyboard.press('Control+A');
    await page.keyboard.type('1/2/2020 9:05');
    await expect(sheet.editor).toHaveValue('1/2/2020 9:05');
    await expect(picker.selectedDay).toHaveText('2');
    await expect(picker.hour).toHaveValue('09');
  });

  test('a typed date and time is stored with Enter', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Arrived').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('1/2/2020 9:05');
    await page.keyboard.press('Enter');

    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.cell(0, 'Arrived')).toHaveText('01/02/2020 09:05');
    await sheet.expectFocusOnActiveCell();
    await expect
      .poll(() => storedValues(table, 'Arrived'))
      .toEqual(['2020-01-02 09:05:00', null]);
  });

  test(
    'a day picked in the calendar keeps the time without its seconds',
    pinsKnownBug('date-time-picker-drops-seconds'),
    async () => {
      const { sheet } = tablePage;
      await sheet.cell(0, 'Arrived').dblclick();
      await picker.day(20).click();

      await expect(sheet.editor).toHaveCount(0);
      await expect(sheet.cell(0, 'Arrived')).toHaveText('03/20/2024 13:45');
      await expect
        .poll(() => storedValues(table, 'Arrived'))
        .toEqual(['2024-03-20 13:45:00', null]);
    },
  );

  test.fixme('a day picked in the calendar keeps the whole time', async () => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Arrived').dblclick();
    await picker.day(20).click();

    await expect
      .poll(() => storedValues(table, 'Arrived'))
      .toEqual(['2024-03-20 13:45:10', null]);
  });

  test('Now and Today set the current time and the start of the current day', async () => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Arrived').dblclick();
    await expect(picker.preset('Now')).toContainText('05/20/2024 10:30');
    await picker.preset('Now').click();
    await expect(sheet.cell(1, 'Arrived')).toHaveText('05/20/2024 10:30');

    await sheet.cell(0, 'Arrived').dblclick();
    await expect(picker.preset('Today')).toContainText('05/20/2024 00:00');
    await picker.preset('Today').click();
    await expect(sheet.cell(0, 'Arrived')).toHaveText('05/20/2024 00:00');

    await expect
      .poll(() => storedValues(table, 'Arrived'))
      .toEqual(['2024-05-20 00:00:00', '2024-05-20 10:30:00']);
  });

  test('a value with time zone is stored in the time zone of the browser', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Zoned').click();
    await page.keyboard.press('Enter');
    await page.keyboard.type('1/2/2020 9:05');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(1, 'Zoned')).toHaveText('01/02/2020 09:05');
    await expect
      .poll(() => storedValues(table, 'Zoned'))
      .toEqual(['2024-03-15 11:45:10+00', '2020-01-02 09:05:00+00']);
  });

  test('a date format and a time format of the column combine in the cells and the input', async ({
    page,
    api,
  }) => {
    const { sheet } = tablePage;
    const formatting = new ColumnFormatting(tablePage.inspector);
    await sheet.columnHeader('Arrived').click();
    await formatting.choose('Date Format', /^European/);
    await formatting.choose('Time Format', /^Long time 24 hr/);
    await formatting.saveButton.click();

    await expect(sheet.cell(0, 'Arrived')).toHaveText('15/03/2024 13:45:10');
    await expect
      .poll(() => api.columnMetadata(table, 'Arrived'))
      .toEqual({ date_format: 'eu', time_format: '24hrLong' });

    await sheet.cell(0, 'Arrived').click();
    await page.keyboard.press('Enter');
    await expect(sheet.editor).toHaveValue('15/03/2024 13:45:10');
    await expect(sheet.editor).toHaveAttribute(
      'placeholder',
      'DD/MM/YYYY HH:mm:ss',
    );
  });
});
