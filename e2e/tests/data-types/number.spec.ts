import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { pinsKnownBug } from '../../support/known-bugs';
import { recordRpcCalls } from '../../support/rpc-log';
import { writeClipboardText } from '../../support/ui/clipboard';
import {
  caretIsInView,
  caretPosition,
} from '../../support/ui/components/typed-cells';
import { fillFormattedInput } from '../../support/ui/components/formatted-input';
import { ColumnFormatting } from '../../support/ui/pages/column-formatting';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

let table: Table;
let tablePage: TablePage;

test.beforeEach(async ({ page, api, schema }) => {
  await runSqlInSchema(
    schema,
    `CREATE TABLE "Measures" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Amount" numeric,
       "Count" integer,
       "Small" smallint,
       "Price" numeric(10, 2),
       "Whole" numeric(10, 0)
     );
     INSERT INTO "Measures" ("Amount", "Count", "Small", "Price") VALUES
       (1234567.891, 1234567, 12, 19.99),
       (-0.5, -42, NULL, NULL),
       (NULL, NULL, NULL, NULL);`,
  );
  table = await api.getTable(schema, 'Measures');
  tablePage = new TablePage(page);
});

/** Opens the editor of a cell with its text selected, so that typing replaces it. */
async function startTyping(row: number, column: string): Promise<void> {
  const { sheet, page } = tablePage;
  await sheet.cell(row, column).click();
  await page.keyboard.press('Enter');
  await page.keyboard.press('Control+A');
}

test.describe('a number cell', () => {
  test.beforeEach(async () => {
    await tablePage.goto(table);
  });

  test('shows the number with the digit grouping of the browser language, aligned right', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Amount')).toHaveText('1,234,567.891');
    await expect(sheet.cell(0, 'Count')).toHaveText('1,234,567');
    await expect(sheet.cell(1, 'Amount')).toHaveText('-0.5');
    await expect(sheet.cell(2, 'Amount')).toHaveText('NULL');
    await expect(sheet.focusTarget(sheet.cell(0, 'Amount'))).toHaveCSS(
      'text-align',
      'right',
    );
  });

  test('Enter opens the number with its grouping and the cursor at its end', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Amount').click();
    await page.keyboard.press('Enter');

    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('1,234,567.891');
    await expect.poll(() => caretPosition(sheet.editor)).toBe(13);
  });

  test('typed digits are grouped while typing, with the cursor after the last one', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await startTyping(2, 'Amount');
    await page.keyboard.type('1234');
    await expect(sheet.editor).toHaveValue('1,234');
    await expect.poll(() => caretPosition(sheet.editor)).toBe(5);

    await page.keyboard.type('567.5');
    await expect(sheet.editor).toHaveValue('1,234,567.5');
    await expect.poll(() => caretPosition(sheet.editor)).toBe(11);

    await page.keyboard.press('Enter');
    await expect(sheet.cell(2, 'Amount')).toHaveText('1,234,567.5');
    await sheet.expectFocusOnActiveCell();
    await expect
      .poll(() => storedValues(table, 'Amount'))
      .toEqual(['1234567.891', '-0.5', '1234567.5']);

    await page.keyboard.press('Enter');
    await expect(sheet.editor).toHaveValue('1,234,567.5');
  });

  test('a click on another cell stores the typed number once and selects that cell', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    const rpcCalls = recordRpcCalls(page);
    await startTyping(2, 'Amount');
    await page.keyboard.type('1234.5');
    await sheet.cell(0, 'Count').click();

    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.cell(0, 'Count')).toHaveAttribute('data-cell-active');
    await expect(sheet.cell(2, 'Amount')).toHaveText('1,234.5');
    await expect
      .poll(() => storedValues(table, 'Amount'))
      .toEqual(['1234567.891', '-0.5', '1234.5']);
    expect(rpcCalls).toEqual(['records.patch']);
  });

  test('Escape discards the typed number', async ({ page }) => {
    const { sheet } = tablePage;
    const rpcCalls = recordRpcCalls(page);
    await startTyping(0, 'Amount');
    await page.keyboard.type('5');
    await expect(sheet.editor).toHaveValue('5');
    await page.keyboard.press('Escape');

    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.cell(0, 'Amount')).toHaveText('1,234,567.891');
    await sheet.expectFocusOnActiveCell();
    expect(rpcCalls).not.toContain('records.patch');
    expect(await storedValues(table, 'Amount')).toEqual([
      '1234567.891',
      '-0.5',
      null,
    ]);
  });

  test('a digit typed in the middle regroups the number and keeps the cursor after it', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await startTyping(2, 'Amount');
    await page.keyboard.type('1234.5');
    for (let step = 0; step < 3; step += 1) {
      await page.keyboard.press('ArrowLeft');
    }
    await page.keyboard.type('9');

    await expect(sheet.editor).toHaveValue('12,394.5');
    await expect.poll(() => caretPosition(sheet.editor)).toBe(5);
  });

  test('a decimal point typed in the integer part moves the decimal point there', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await startTyping(2, 'Amount');
    await page.keyboard.type('12394.5');
    for (let step = 0; step < 3; step += 1) {
      await page.keyboard.press('ArrowLeft');
    }
    await page.keyboard.type('.');

    await expect(sheet.editor).toHaveValue('1,239.45');
    await expect.poll(() => caretPosition(sheet.editor)).toBe(6);
  });

  test('letters, commas and a minus after the first digit are ignored', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await startTyping(2, 'Amount');
    await page.keyboard.type('12');
    await page.keyboard.type('x,-e');

    await expect(sheet.editor).toHaveValue('12');
    await expect.poll(() => caretPosition(sheet.editor)).toBe(2);
  });

  test('a minus typed at the start makes the number negative', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Count').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Home');
    await page.keyboard.type('-');
    await expect(sheet.editor).toHaveValue('-1,234,567');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(0, 'Count')).toHaveText('-1,234,567');
    await expect
      .poll(() => storedValues(table, 'Count'))
      .toEqual(['-1234567', '-42', null]);
  });

  test('an input without a number stores NULL', async ({ page }) => {
    const { sheet } = tablePage;
    await startTyping(0, 'Amount');
    await page.keyboard.press('Backspace');
    await page.keyboard.press('Enter');
    await startTyping(1, 'Amount');
    await page.keyboard.type('-');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(0, 'Amount')).toHaveText('NULL');
    await expect(sheet.cell(1, 'Amount')).toHaveText('NULL');
    await expect
      .poll(() => storedValues(table, 'Amount'))
      .toEqual([null, null, null]);
  });

  test('a pasted number is grouped like a typed one', async ({ page }) => {
    const { sheet } = tablePage;
    await writeClipboardText(page, '98765.4321');
    await startTyping(2, 'Amount');
    await page.keyboard.press('Control+V');

    await expect(sheet.editor).toHaveValue('98,765.4321');
    await expect.poll(() => caretPosition(sheet.editor)).toBe(11);
  });

  test('integer columns and numerics without decimal places ignore a typed decimal point', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await startTyping(2, 'Count');
    await page.keyboard.type('12.5');
    await expect(sheet.editor).toHaveValue('125');
    await page.keyboard.press('Enter');
    await startTyping(1, 'Whole');
    await page.keyboard.type('12.5');
    await expect(sheet.editor).toHaveValue('125');
    await page.keyboard.press('Enter');

    await expect
      .poll(() => storedValues(table, 'Count'))
      .toEqual(['1234567', '-42', '125']);
    await expect
      .poll(() => storedValues(table, 'Whole'))
      .toEqual([null, '125', null]);
  });

  test('a number beyond the range of the column type stays in the cell with the database error', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    const small = sheet.cell(0, 'Small');
    await startTyping(0, 'Small');
    await page.keyboard.type('40000');
    await page.keyboard.press('Enter');

    await expect(sheet.errorIndicator(small)).toBeVisible();
    await expect(small).toHaveText('40,000');
    await expect(sheet.cellErrors).toContainText(
      'value "40000" is out of range for type smallint',
    );
    expect(await storedValues(table, 'Small')).toEqual(['12', null, null]);
  });

  test('the cell shows the number as the database rounded it to the scale of the column', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await startTyping(0, 'Price');
    await page.keyboard.type('1.239');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(0, 'Price')).toHaveText('1.24');
    await expect
      .poll(() => storedValues(table, 'Price'))
      .toEqual(['1.24', null, null]);
  });
});

test.describe('a number wider than its cell', () => {
  test.beforeEach(async ({ api }) => {
    await api.setColumnMetadata(table, 'Amount', { display_width: 90 });
    await tablePage.goto(table);
  });

  test('the input scrolls to keep the cursor in view while digits are typed in the middle', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Amount').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Home');
    for (let step = 0; step < 7; step += 1) {
      await page.keyboard.press('ArrowRight');
    }
    await page.keyboard.type('9999');

    await expect(sheet.editor).toHaveValue('12,345,999,967.891');
    await expect.poll(() => caretPosition(sheet.editor)).toBe(12);
    await expect.poll(() => caretIsInView(sheet.editor)).toBe(true);
  });
});

test.describe('very large and very small numbers', () => {
  test.beforeEach(async ({ schema }) => {
    await runSqlInSchema(
      schema,
      `ALTER TABLE "Measures" ADD COLUMN "Big" bigint, ADD COLUMN "Ratio" double precision;
       UPDATE "Measures" SET "Big" = 9007199254740993, "Ratio" = 1e21 WHERE id = 1;
       UPDATE "Measures" SET "Ratio" = 0.000000001,
         "Amount" = 123456789012345678901234567890.5 WHERE id = 2;`,
    );
    await tablePage.goto(table);
  });

  test(
    'a bigint beyond the precision of the browser is shown with other last digits',
    pinsKnownBug('number-precision-lost-in-display'),
    async () => {
      await expect(tablePage.sheet.cell(0, 'Big')).toHaveText(
        '9,007,199,254,740,992',
      );
    },
  );

  test.fixme('a bigint beyond the precision of the browser is shown with all its digits', async () => {
    await expect(tablePage.sheet.cell(0, 'Big')).toHaveText(
      '9,007,199,254,740,993',
    );
  });

  test(
    'numbers that the browser writes with an exponent are shown without its sign',
    pinsKnownBug('number-exponent-display'),
    async () => {
      const { sheet } = tablePage;
      await expect(sheet.cell(0, 'Ratio')).toHaveText('121');
      await expect(sheet.cell(1, 'Ratio')).toHaveText('19');
      await expect(sheet.cell(1, 'Amount')).toHaveText('1.234567890123456829');
    },
  );

  test.fixme('numbers that the browser writes with an exponent are shown in full', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Ratio')).toHaveText(
      '1,000,000,000,000,000,000,000',
    );
    await expect(sheet.cell(1, 'Ratio')).toHaveText('0.000000001');
    await expect(sheet.cell(1, 'Amount')).toHaveText(
      '123,456,789,012,345,678,901,234,567,890.5',
    );
  });
});

test.describe('a number cell that shows fewer decimal places than stored', () => {
  test.beforeEach(async ({ api }) => {
    await api.setColumnMetadata(table, 'Amount', {
      num_min_frac_digits: 2,
      num_max_frac_digits: 2,
    });
    await tablePage.goto(table);
  });

  test(
    'opens the rounded number, and an edit stores it rounded',
    pinsKnownBug('number-editor-rounds-to-decimal-places'),
    async ({ page }) => {
      const { sheet } = tablePage;
      await sheet.cell(0, 'Amount').click();
      await page.keyboard.press('Enter');
      await expect(sheet.editor).toHaveValue('1,234,567.89');
      await page.keyboard.press('Home');
      await page.keyboard.type('1');
      await page.keyboard.press('Enter');

      await expect
        .poll(() => storedValues(table, 'Amount'))
        .toEqual(['11234567.89', '-0.5', null]);
    },
  );

  test.fixme('opens the whole number, and an edit keeps its decimals', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Amount').click();
    await page.keyboard.press('Enter');
    await expect(sheet.editor).toHaveValue('1,234,567.891');
    await page.keyboard.press('Home');
    await page.keyboard.type('1');
    await page.keyboard.press('Enter');

    await expect
      .poll(() => storedValues(table, 'Amount'))
      .toEqual(['11234567.891', '-0.5', null]);
  });
});

test.describe('the number formatting of a column', () => {
  let formatting: ColumnFormatting;

  test.beforeEach(async () => {
    formatting = new ColumnFormatting(tablePage.inspector);
    await tablePage.goto(table);
    await tablePage.sheet.columnHeader('Amount').click();
  });

  test('decimal places and digit grouping change the cells once saved', async ({
    api,
  }) => {
    const { sheet } = tablePage;
    await fillFormattedInput(formatting.field('Decimal Places'), '2');
    await formatting.choose('Digit Grouping', 'Never');
    await formatting.saveButton.click();

    await expect(sheet.cell(0, 'Amount')).toHaveText('1234567.89');
    await expect(sheet.cell(1, 'Amount')).toHaveText('-0.50');
    await expect
      .poll(() => api.columnMetadata(table, 'Amount'))
      .toEqual({
        num_min_frac_digits: 2,
        num_max_frac_digits: 2,
        num_grouping: 'never',
      });
  });

  test('a format changes the separators of the cells and of the input', async ({
    page,
    api,
  }) => {
    const { sheet } = tablePage;
    await formatting.choose('Format', '1.234.567,89');
    await formatting.saveButton.click();

    await expect(sheet.cell(0, 'Amount')).toHaveText('1.234.567,891');
    await expect
      .poll(() => api.columnMetadata(table, 'Amount'))
      .toMatchObject({ num_format: 'german' });

    await startTyping(2, 'Amount');
    await page.keyboard.type('1234,5');
    await expect(sheet.editor).toHaveValue('1.234,5');
    await page.keyboard.press('Enter');
    await expect
      .poll(() => storedValues(table, 'Amount'))
      .toEqual(['1234567.891', '-0.5', '1234.5']);
  });
});
