import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { pinsKnownBug } from '../../support/known-bugs';
import { TablePage } from '../../support/ui/pages/table-page';
import { delayFirstResponse } from './late-response';
import { storedValues } from './stored-values';

test.describe('two cells of one record, where the first save is answered after the second', () => {
  let table: Table;
  let tablePage: TablePage;
  let answerFirstSave: () => void;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Items" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Cost" numeric(10, 2),
         "Price" numeric(10, 2)
       );
       INSERT INTO "Items" ("Cost", "Price") VALUES (1.5, 19.99);`,
    );
    table = await api.getTable(schema, 'Items');
    tablePage = new TablePage(page);
    await tablePage.goto(table);
    answerFirstSave = await delayFirstResponse(page, 'records.patch');

    const { sheet } = tablePage;
    await sheet.editFormattedCell(sheet.cell(0, 'Cost'), '5.555');
    await expect.poll(() => storedValues(table, 'Cost')).toEqual(['5.56']);
    await sheet.editFormattedCell(sheet.cell(0, 'Price'), '1.239');
    await expect(sheet.cell(0, 'Price')).toHaveText('1.24');
    await expect(sheet.cell(0, 'Cost')).toHaveText('5.555');
  });

  test(
    'the late answer puts back the old value of the second cell',
    pinsKnownBug('late-save-response-reverts-newer-edit'),
    async () => {
      const { sheet } = tablePage;
      answerFirstSave();

      await expect(sheet.cell(0, 'Cost')).toHaveText('5.56');
      await expect(sheet.cell(0, 'Price')).toHaveText('19.99');
      expect(await storedValues(table, 'Price')).toEqual(['1.24']);
    },
  );

  test.fixme('the late answer keeps the value of the second cell', async () => {
    const { sheet } = tablePage;
    answerFirstSave();

    await expect(sheet.cell(0, 'Cost')).toHaveText('5.56');
    await expect(sheet.cell(0, 'Price')).toHaveText('1.24');
  });
});
