import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { recordRpcCalls } from '../../support/rpc-log';
import { CellDropdown } from '../../support/ui/components/cell-dropdown';
import { dropdownOffset } from '../../support/ui/components/typed-cells';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

let table: Table;
let tablePage: TablePage;
let dropdown: CellDropdown;

test.beforeEach(async ({ page, api, schema }) => {
  await runSqlInSchema(
    schema,
    `CREATE TYPE "Level" AS ENUM ('low', 'mid', 'high');
     CREATE TABLE "Tickets" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Priority" "Level",
       "Severity" "Level" NOT NULL DEFAULT 'low'
     );
     INSERT INTO "Tickets" ("Priority", "Severity") VALUES
       ('high', 'mid'), (NULL, 'low');`,
  );
  table = await api.getTable(schema, 'Tickets');
  tablePage = new TablePage(page);
  dropdown = new CellDropdown(page);
  await tablePage.goto(table);
});

test.describe('an enum cell', () => {
  test('shows its value as text, and NULL', async () => {
    await expect(tablePage.sheet.cell(0, 'Priority')).toHaveText('high');
    await expect(tablePage.sheet.cell(1, 'Priority')).toHaveText('NULL');
  });

  test('a click on a cell that is not active only selects it', async () => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Priority').click();

    await expect(sheet.cell(0, 'Priority')).toHaveAttribute('data-cell-active');
    await expect(dropdown.root).toHaveCount(0);
  });

  test('a click on the active cell lists NULL and the values of the type, without a request', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Priority').click();
    const rpcCalls = recordRpcCalls(page);
    await sheet.cell(0, 'Priority').click();

    await expect(dropdown.options).toHaveText(['', 'low', 'mid', 'high']);
    await expect(dropdown.selectedOption).toHaveText('high');
    expect(rpcCalls).toEqual([]);
    expect(await storedValues(table, 'Priority')).toEqual(['high', null]);
  });

  test('Enter opens the list under the cell', async ({ page }) => {
    const priority = tablePage.sheet.cell(0, 'Priority');
    await priority.click();
    await page.keyboard.press('Enter');

    await expect(dropdown.options).toHaveText(['', 'low', 'mid', 'high']);
    await expect(dropdown.highlightedOption).toHaveText('high');
    await expect
      .poll(() => dropdownOffset(dropdown.root, priority))
      .toEqual({ x: expect.closeTo(0, -1), y: expect.closeTo(0, -1) });
  });

  test('a double click on a cell that is not active opens the list', async () => {
    await tablePage.sheet.cell(0, 'Priority').dblclick();

    await expect(dropdown.selectedOption).toHaveText('high');
  });

  test('the arrow keys move the highlight and Enter stores the highlighted value', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Priority').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('ArrowUp');
    await page.keyboard.press('ArrowUp');
    await page.keyboard.press('ArrowDown');
    await expect(dropdown.highlightedOption).toHaveText('mid');
    await page.keyboard.press('Enter');

    await expect(dropdown.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Priority')).toHaveText('mid');
    await sheet.expectFocusOnActiveCell();
    await expect
      .poll(() => storedValues(table, 'Priority'))
      .toEqual(['mid', null]);
  });

  test('ArrowDown on the last value highlights the first one', async ({
    page,
  }) => {
    await tablePage.sheet.cell(0, 'Priority').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('ArrowDown');

    await expect(dropdown.highlightedOption).toHaveText('');
  });

  test('the empty option stores NULL', async () => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Priority').dblclick();
    await dropdown.option('').click();

    await expect(sheet.cell(0, 'Priority')).toHaveText('NULL');
    await expect
      .poll(() => storedValues(table, 'Priority'))
      .toEqual([null, null]);
  });

  test('a column that disallows NULL offers no empty option', async () => {
    await tablePage.sheet.cell(0, 'Severity').dblclick();

    await expect(dropdown.options).toHaveText(['low', 'mid', 'high']);
  });

  test('Escape closes the list and keeps the value', async ({ page }) => {
    const { sheet } = tablePage;
    const rpcCalls = recordRpcCalls(page);
    await sheet.cell(0, 'Priority').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('ArrowUp');
    await expect(dropdown.highlightedOption).toHaveText('mid');
    await page.keyboard.press('Escape');

    await expect(dropdown.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Priority')).toHaveText('high');
    await sheet.expectFocusOnActiveCell();
    expect(rpcCalls).not.toContain('records.patch');
  });

  test('Tab closes the list and moves to the next cell without storing', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Priority').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('ArrowUp');
    await expect(dropdown.highlightedOption).toHaveText('mid');
    await page.keyboard.press('Tab');

    await expect(dropdown.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Severity')).toHaveAttribute('data-cell-active');
    await sheet.expectFocusOnActiveCell();
    await expect(sheet.cell(0, 'Priority')).toHaveText('high');
    expect(await storedValues(table, 'Priority')).toEqual(['high', null]);
  });

  test('ArrowLeft closes the list and moves to the previous cell without storing', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Severity').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('ArrowUp');
    await expect(dropdown.highlightedOption).toHaveText('low');
    await page.keyboard.press('ArrowLeft');

    await expect(dropdown.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Priority')).toHaveAttribute('data-cell-active');
    await expect(sheet.cell(0, 'Severity')).toHaveText('mid');
    expect(await storedValues(table, 'Severity')).toEqual(['mid', 'low']);
  });
});
