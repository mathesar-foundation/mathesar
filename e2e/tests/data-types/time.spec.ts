import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { pinsKnownBug } from '../../support/known-bugs';
import { DateTimePicker } from '../../support/ui/components/date-time-picker';
import { openSelect } from '../../support/ui/components/select';
import { ColumnFormatting } from '../../support/ui/pages/column-formatting';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

let table: Table;
let tablePage: TablePage;
let picker: DateTimePicker;

test.beforeEach(async ({ page, api, schema }) => {
  await page.clock.setFixedTime(new Date('2024-05-20T10:30:00Z'));
  await runSqlInSchema(
    schema,
    `CREATE TABLE "Shifts" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Starts" time,
       "Zoned" time with time zone,
       "Note" text
     );
     INSERT INTO "Shifts" ("Starts", "Zoned", "Note") VALUES
       ('13:45:10', '13:45:10+02', 'early'), (NULL, NULL, 'open');`,
  );
  table = await api.getTable(schema, 'Shifts');
  tablePage = new TablePage(page);
  picker = new DateTimePicker(page);
});

test.describe('a time cell', () => {
  test.beforeEach(async () => {
    await tablePage.goto(table);
  });

  test('shows hours and minutes, with a time zone converted to that of the browser', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Starts')).toHaveText('13:45');
    await expect(sheet.cell(0, 'Zoned')).toHaveText('11:45');
    await expect(sheet.cell(1, 'Starts')).toHaveText('NULL');
  });

  test('Enter opens the time and the hour and minute fields, which stay open while typing', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Starts').click();
    await page.keyboard.press('Enter');

    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('13:45');
    await expect(sheet.editor).toHaveAttribute('placeholder', 'HH:mm');
    await expect(picker.hour).toHaveValue('13');
    await expect(picker.minute).toHaveValue('45');

    await page.keyboard.press('Control+A');
    await page.keyboard.type('9:05');
    await expect(sheet.editor).toHaveValue('9:05');
    await expect(picker.hour).toHaveValue('09');
    await expect(picker.minute).toHaveValue('05');
  });

  test('a double click opens the time and the hour and minute fields, which stay open while typing', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Starts').dblclick();

    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('13:45');
    await expect(picker.hour).toHaveValue('13');

    await page.keyboard.press('Control+A');
    await page.keyboard.type('9:05');
    await expect(sheet.editor).toHaveValue('9:05');
    await expect(picker.hour).toHaveValue('09');
  });

  test('a typed time is stored with Enter', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Starts').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('9:05');
    await page.keyboard.press('Enter');

    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.cell(0, 'Starts')).toHaveText('09:05');
    await sheet.expectFocusOnActiveCell();
    await expect
      .poll(() => storedValues(table, 'Starts'))
      .toEqual(['09:05:00', null]);
  });

  test(
    'the arrow of the hour field changes the time without its seconds, which a click elsewhere stores',
    pinsKnownBug('date-time-picker-drops-seconds'),
    async () => {
      const { sheet } = tablePage;
      await sheet.cell(0, 'Starts').dblclick();
      await picker.hourUpArrow.click();

      await expect(sheet.editor).toHaveValue('14:45');
      await sheet.cell(1, 'Note').click();
      await expect(sheet.cell(0, 'Starts')).toHaveText('14:45');
      await expect
        .poll(() => storedValues(table, 'Starts'))
        .toEqual(['14:45:00', null]);
    },
  );

  test.fixme('the arrow of the hour field changes only the hour, which a click elsewhere stores', async () => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Starts').dblclick();
    await picker.hourUpArrow.click();

    await expect(sheet.editor).toHaveValue('14:45');
    await sheet.cell(1, 'Note').click();
    await expect
      .poll(() => storedValues(table, 'Starts'))
      .toEqual(['14:45:10', null]);
  });

  test('Now sets the current time', async () => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Starts').dblclick();
    await expect(picker.preset('Now')).toContainText('10:30');
    await picker.preset('Now').click();

    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.cell(1, 'Starts')).toHaveText('10:30');
    await expect
      .poll(() => storedValues(table, 'Starts'))
      .toEqual(['13:45:10', '10:30:00']);
  });

  test('a time with time zone is stored in the time zone of the browser', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Zoned').click();
    await page.keyboard.press('Enter');
    await page.keyboard.type('9:05');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(1, 'Zoned')).toHaveText('09:05');
    await expect
      .poll(() => storedValues(table, 'Zoned'))
      .toEqual(['13:45:10+02', '09:05:00+00']);
  });
});

test.describe('the time format of a column', () => {
  test('offers four formats, each shown with the current time', async () => {
    const formatting = new ColumnFormatting(tablePage.inspector);
    await tablePage.goto(table);
    await tablePage.sheet.columnHeader('Starts').click();
    const options = await openSelect(formatting.select('Time Format'));

    await expect(options.getByRole('option')).toHaveText([
      'Short time 24 hr (10:30)',
      'Long time 24 hr (10:30:00)',
      'Short time 12 hr (10:30 am)',
      'Long time 12 hr (10:30:00 am)',
    ]);
  });

  test('changes the cells and the input once saved', async ({ page, api }) => {
    const { sheet } = tablePage;
    const formatting = new ColumnFormatting(tablePage.inspector);
    await tablePage.goto(table);
    await sheet.columnHeader('Starts').click();
    await formatting.choose('Time Format', /^Short time 12 hr/);
    await formatting.saveButton.click();

    await expect(sheet.cell(0, 'Starts')).toHaveText('01:45 pm');
    await expect
      .poll(() => api.columnMetadata(table, 'Starts'))
      .toEqual({ time_format: '12hr' });

    await sheet.cell(0, 'Starts').click();
    await page.keyboard.press('Enter');
    await expect(sheet.editor).toHaveValue('01:45 pm');
    await expect(sheet.editor).toHaveAttribute('placeholder', 'hh:mm a');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('9:05 PM');
    await page.keyboard.press('Enter');
    await expect
      .poll(() => storedValues(table, 'Starts'))
      .toEqual(['21:05:00', null]);
  });

  test(
    'in the long 12 hour format, a typed afternoon time is stored as a morning time',
    pinsKnownBug('time-long-12-hour-format-ignores-pm'),
    async ({ page, api }) => {
      const { sheet } = tablePage;
      await api.setColumnMetadata(table, 'Starts', { time_format: '12hrLong' });
      await tablePage.goto(table);
      await sheet.cell(1, 'Starts').click();
      await page.keyboard.press('Enter');
      await page.keyboard.type('09:05:30 PM');
      await page.keyboard.press('Enter');

      await expect(sheet.cell(1, 'Starts')).toHaveText('09:05:30 am');
      await expect
        .poll(() => storedValues(table, 'Starts'))
        .toEqual(['13:45:10', '09:05:30']);
    },
  );

  test.fixme('in the long 12 hour format, a typed afternoon time is stored as such', async ({
    page,
    api,
  }) => {
    const { sheet } = tablePage;
    await api.setColumnMetadata(table, 'Starts', { time_format: '12hrLong' });
    await tablePage.goto(table);
    await sheet.cell(1, 'Starts').click();
    await page.keyboard.press('Enter');
    await page.keyboard.type('09:05:30 PM');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(1, 'Starts')).toHaveText('09:05:30 pm');
    await expect
      .poll(() => storedValues(table, 'Starts'))
      .toEqual(['13:45:10', '21:05:30']);
  });
});
