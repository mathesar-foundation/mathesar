import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { ColumnFormatting } from '../../support/ui/pages/column-formatting';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

let table: Table;
let tablePage: TablePage;

test.beforeEach(async ({ page, api, schema }) => {
  await runSqlInSchema(
    schema,
    `CREATE TABLE "Tasks" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Spent" interval
     );
     INSERT INTO "Tasks" ("Spent") VALUES
       ('1 day 02:30:00'), ('00:00:45'), (NULL);`,
  );
  table = await api.getTable(schema, 'Tasks');
  tablePage = new TablePage(page);
  await tablePage.goto(table);
});

/** Opens the editor of a cell with its text selected, so that typing replaces it. */
async function startTyping(row: number): Promise<void> {
  const { sheet, page } = tablePage;
  await sheet.cell(row, 'Spent').click();
  await page.keyboard.press('Enter');
  await page.keyboard.press('Control+A');
}

test.describe('a duration cell', () => {
  test('shows minutes and seconds aligned right, with the days and hours counted as minutes', async () => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Spent')).toHaveText('1590:00');
    await expect(sheet.cell(1, 'Spent')).toHaveText('00:45');
    await expect(sheet.cell(2, 'Spent')).toHaveText('NULL');
    await expect(sheet.focusTarget(sheet.cell(0, 'Spent'))).toHaveCSS(
      'text-align',
      'right',
    );
  });

  test('Enter opens the duration with its format as the placeholder', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Spent').click();
    await page.keyboard.press('Enter');

    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('00:45');
    await expect(sheet.editor).toHaveAttribute('placeholder', 'mm:ss');
  });

  test('typed minutes and seconds are stored with Enter', async ({ page }) => {
    const { sheet } = tablePage;
    await startTyping(2);
    await page.keyboard.type('90:30');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(2, 'Spent')).toHaveText('90:30');
    await sheet.expectFocusOnActiveCell();
    await expect
      .poll(() => storedValues(table, 'Spent'))
      .toEqual(['1 day 02:30:00', '00:00:45', '01:30:30']);
  });

  test('a click on another cell stores the typed duration', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await startTyping(2);
    await page.keyboard.type('2:05');
    await sheet.cell(0, 'Spent').click();

    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.cell(2, 'Spent')).toHaveText('02:05');
    await expect
      .poll(() => storedValues(table, 'Spent'))
      .toEqual(['1 day 02:30:00', '00:00:45', '00:02:05']);
  });

  test('a number without a colon counts as seconds', async ({ page }) => {
    const { sheet } = tablePage;
    await startTyping(2);
    await page.keyboard.type('75');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(2, 'Spent')).toHaveText('01:15');
    await expect
      .poll(() => storedValues(table, 'Spent'))
      .toEqual(['1 day 02:30:00', '00:00:45', '00:01:15']);
  });

  test('letters and a colon beyond the format are ignored', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await startTyping(2);
    await page.keyboard.type('1:2x:3');

    await expect(sheet.editor).toHaveValue('1:23');
  });

  test('an emptied input stores NULL', async ({ page }) => {
    const { sheet } = tablePage;
    await startTyping(1);
    await page.keyboard.press('Backspace');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(1, 'Spent')).toHaveText('NULL');
    await expect
      .poll(() => storedValues(table, 'Spent'))
      .toEqual(['1 day 02:30:00', null, null]);
  });
});

test.describe('the duration formatting of a column', () => {
  let formatting: ColumnFormatting;

  test.beforeEach(async () => {
    formatting = new ColumnFormatting(tablePage.inspector);
    await tablePage.sheet.columnHeader('Spent').click();
  });

  test('the largest and smallest unit follow each other and name the format', async () => {
    await expect(formatting.select('Max Time Unit')).toHaveText('Minutes');
    await expect(formatting.select('Min Time Unit')).toHaveText('Seconds');
    await expect(formatting.durationFormat).toHaveText('Format: mm:ss');

    await formatting.choose('Min Time Unit', 'Days');
    await expect(formatting.select('Max Time Unit')).toHaveText('Days');
    await expect(formatting.durationFormat).toHaveText('Format: D');

    await formatting.choose('Max Time Unit', 'Milliseconds');
    await expect(formatting.select('Min Time Unit')).toHaveText('Milliseconds');
    await expect(formatting.durationFormat).toHaveText('Format: SSS');
  });

  test('days and hours change the cells and the input once saved', async ({
    page,
    api,
  }) => {
    const { sheet } = tablePage;
    await formatting.choose('Max Time Unit', 'Days');
    await formatting.choose('Min Time Unit', 'Hours');
    await expect(formatting.durationFormat).toHaveText('Format: D:HH');
    await formatting.saveButton.click();

    await expect(sheet.cell(0, 'Spent')).toHaveText('1:2.5');
    await expect(sheet.cell(1, 'Spent')).toHaveText('0:0.013');
    await expect
      .poll(() => api.columnMetadata(table, 'Spent'))
      .toEqual({ duration_max: 'd', duration_min: 'h' });

    await startTyping(2);
    await expect(sheet.editor).toHaveAttribute('placeholder', 'D:HH');
    await page.keyboard.type('2:5');
    await page.keyboard.press('Enter');
    await expect(sheet.cell(2, 'Spent')).toHaveText('2:05');
    await expect
      .poll(() => storedValues(table, 'Spent'))
      .toEqual(['1 day 02:30:00', '00:00:45', '2 days 05:00:00']);
  });
});
