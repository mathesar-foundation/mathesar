import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

test.describe('a text cell with a length limit', () => {
  let table: Table;
  let tablePage: TablePage;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Codes" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Short" varchar(5),
         "Fixed" char(3)
       );
       INSERT INTO "Codes" ("Short", "Fixed") VALUES ('abc', 'ab');`,
    );
    table = await api.getTable(schema, 'Codes');
    tablePage = new TablePage(page);
    await tablePage.goto(table);
  });

  test('stops taking characters at the maximum length', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Short').click();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('abcdefgh');
    await expect(sheet.editor).toHaveValue('abcde');
    await page.keyboard.press('Enter');

    await expect(sheet.cell(0, 'Short')).toHaveText('abcde');
    await expect.poll(() => storedValues(table, 'Short')).toEqual(['abcde']);
  });

  test('of fixed length opens the value padded with spaces to that length', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Fixed')).toHaveText('ab');
    await sheet.cell(0, 'Fixed').click();
    await page.keyboard.press('Enter');

    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('ab ');
  });
});
