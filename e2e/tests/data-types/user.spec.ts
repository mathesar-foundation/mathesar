import {
  type Table,
  type User,
  runSqlInSchema,
} from '../../support/api/mathesar';
import { env } from '../../support/env';
import { test as base, expect } from '../../support/fixtures';
import { RowSeeker } from '../../support/ui/components/row-seeker';
import {
  missingUserWarning,
  selectUserButton,
} from '../../support/ui/components/typed-cells';
import { ColumnFormatting } from '../../support/ui/pages/column-formatting';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

const test = base.extend<{ teammate: User }>({
  /** A collaborator on `database` with a display name and an email. */
  teammate: async ({ api, database, createUser }, use) => {
    const user = await createUser({
      fullName: 'Grace Hopper',
      email: 'grace@example.org',
    });
    const role = await api.createStoredRole(database);
    await api.addCollaborator(database, user, role);
    await use(user);
  },
});

/** No user has this id. */
const MISSING_USER_ID = 999999;

let table: Table;
let tablePage: TablePage;
let seeker: RowSeeker;

test.beforeEach(async ({ page, api, schema, teammate }) => {
  await runSqlInSchema(
    schema,
    `CREATE TABLE "Jobs" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Owner" integer
     );
     INSERT INTO "Jobs" ("Owner") VALUES
       (${teammate.id}), (NULL), (${MISSING_USER_ID});`,
  );
  table = await api.getTable(schema, 'Jobs');
  await api.makeUserColumn(table, 'Owner');
  tablePage = new TablePage(page);
  seeker = new RowSeeker(page);
});

test.describe('a user cell', () => {
  test.beforeEach(async () => {
    await tablePage.goto(table);
  });

  test('shows the username, and NULL', async ({ teammate }) => {
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Owner')).toHaveText(teammate.username);
    await expect(sheet.cell(1, 'Owner')).toHaveText('NULL');
  });

  test('warns about a user who is not a collaborator, next to the id', async () => {
    const owner = tablePage.sheet.cell(2, 'Owner');
    await expect(owner).toHaveText(String(MISSING_USER_ID));
    await expect(missingUserWarning(owner)).toBeVisible();
  });

  test('a click on the active cell lists the collaborators, and a choice is stored', async ({
    teammate,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Owner').click();
    await expect(seeker.root).toHaveCount(0);
    await sheet.cell(1, 'Owner').click();

    await expect(seeker.search).toBeFocused();
    await expect(seeker.options).toHaveCount(2);
    await expect(seeker.option('admin')).toBeVisible();
    await seeker.option(teammate.username).click();

    await expect(seeker.root).toHaveCount(0);
    await expect(sheet.cell(1, 'Owner')).toHaveText(teammate.username);
    await sheet.expectFocusOnActiveCell();
    await expect
      .poll(() => storedValues(table, 'Owner'))
      .toEqual([
        String(teammate.id),
        String(teammate.id),
        String(MISSING_USER_ID),
      ]);
  });

  test('Enter opens the list with the current user chosen', async ({
    page,
    teammate,
  }) => {
    await tablePage.sheet.cell(0, 'Owner').click();
    await page.keyboard.press('Enter');

    await expect(seeker.search).toBeFocused();
    await expect(seeker.option(teammate.username)).toHaveAttribute(
      'aria-selected',
      'true',
    );
  });

  test('a double click on a cell that is not active opens the list', async () => {
    await tablePage.sheet.cell(1, 'Owner').dblclick();

    await expect(seeker.search).toBeFocused();
  });

  test('the button of the active cell opens the list', async () => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Owner').click();
    await selectUserButton(sheet.cell(1, 'Owner')).click();

    await expect(seeker.search).toBeFocused();
  });

  test('Escape closes the list and keeps the user', async ({
    page,
    teammate,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Owner').click();
    await page.keyboard.press('Enter');
    await expect(seeker.search).toBeFocused();
    await page.keyboard.press('Escape');

    await expect(seeker.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Owner')).toHaveText(teammate.username);
    await sheet.expectFocusOnActiveCell();
    expect(await storedValues(table, 'Owner')).toEqual([
      String(teammate.id),
      null,
      String(MISSING_USER_ID),
    ]);
  });

  test('the search narrows the list and says when no user matches', async ({
    page,
  }) => {
    await tablePage.sheet.cell(1, 'Owner').click();
    await page.keyboard.press('Enter');
    await seeker.search.fill('adm');
    await expect(seeker.options).toHaveText(['admin']);

    await seeker.search.fill('nobody');
    await expect(seeker.options).toHaveCount(0);
    await expect(seeker.emptyMessage).toBeVisible();
  });

  test('the search also finds a user by display name and by email', async ({
    page,
    teammate,
  }) => {
    await tablePage.sheet.cell(1, 'Owner').click();
    await page.keyboard.press('Enter');
    await seeker.search.fill('Hopper');
    await expect(seeker.options).toHaveText([teammate.username]);

    await seeker.search.fill('');
    await expect(seeker.options).toHaveCount(2);
    await seeker.search.fill('grace@example');
    await expect(seeker.options).toHaveText([teammate.username]);
  });

  test('a click on the user that the cell holds closes the list and keeps the user', async ({
    page,
    teammate,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'Owner').click();
    await page.keyboard.press('Enter');
    await seeker.option(teammate.username).click();

    await expect(seeker.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Owner')).toHaveText(teammate.username);
    expect(await storedValues(table, 'Owner')).toEqual([
      String(teammate.id),
      null,
      String(MISSING_USER_ID),
    ]);
  });
});

test.describe('the user formatting of a column', () => {
  test('Display Name represents each user once saved, and the id stands in for a missing name', async ({
    api,
  }) => {
    const { sheet } = tablePage;
    const formatting = new ColumnFormatting(tablePage.inspector);
    const admin = await api.findUser(env.admin.username);
    await runSqlInSchema(
      table.schema,
      `UPDATE "Jobs" SET "Owner" = ${admin?.id} WHERE id = 2;`,
    );
    await tablePage.goto(table);
    await sheet.columnHeader('Owner').click();
    await expect(formatting.select('Field to represent each user')).toHaveText(
      'Username',
    );
    await formatting.choose('Field to represent each user', 'Display Name');
    await formatting.saveButton.click();

    await expect(sheet.cell(0, 'Owner')).toHaveText('Grace Hopper');
    await expect(sheet.cell(1, 'Owner')).toHaveText(String(admin?.id));
    await expect
      .poll(() => api.columnMetadata(table, 'Owner'))
      .toEqual({ user_display_field: 'full_name' });
  });

  test('Email represents each user', async ({ api }) => {
    await api.setColumnMetadata(table, 'Owner', {
      user_display_field: 'email',
    });
    await tablePage.goto(table);

    await expect(tablePage.sheet.cell(0, 'Owner')).toHaveText(
      'grace@example.org',
    );
  });
});
