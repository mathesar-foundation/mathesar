import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import {
  arrayItems,
  cellCheckbox,
} from '../../support/ui/components/typed-cells';
import { TablePage } from '../../support/ui/pages/table-page';

test.describe('the Cell tab of the inspector', () => {
  let table: Table;
  let tablePage: TablePage;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Samples" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Note" text,
         "Done" boolean,
         "Amount" numeric,
         "Day" date,
         "Tags" text[]
       );
       INSERT INTO "Samples" ("Note", "Done", "Amount", "Day", "Tags") VALUES
         (E'line one\\nline two', true, 1234567.891, '2024-03-15', '{x,"y z",NULL}'),
         (NULL, NULL, NULL, NULL, '{}');`,
    );
    table = await api.getTable(schema, 'Samples');
    await api.setColumnMetadata(table, 'Day', { date_format: 'friendly' });
    tablePage = new TablePage(page);
    await tablePage.goto(table);
  });

  test('shows a text in full, with its line breaks', async () => {
    const { sheet, inspector } = tablePage;
    await sheet.cell(0, 'Note').click();
    await inspector.tab('Cell').click();

    await expect(inspector.panel).toHaveText(/line one\nline two/);
  });

  test('shows a boolean as a checkbox that cannot be changed', async () => {
    const { sheet, inspector } = tablePage;
    await sheet.cell(0, 'Done').click({ position: { x: 100, y: 10 } });
    await inspector.tab('Cell').click();

    await expect(cellCheckbox(inspector.panel)).toBeChecked();
    await expect(cellCheckbox(inspector.panel)).toBeDisabled();
  });

  test('shows numbers and dates as the column formats them, and NULL', async () => {
    const { sheet, inspector } = tablePage;
    await sheet.cell(0, 'Amount').click();
    await inspector.tab('Cell').click();
    await expect(inspector.panel).toHaveText(/Content\s*1,234,567\.891/);

    await sheet.cell(0, 'Day').click();
    await expect(inspector.panel).toHaveText(/Content\s*15 Mar 2024/);

    await sheet.cell(1, 'Day').click();
    await expect(inspector.panel).toHaveText(/Content\s*NULL/);
  });

  test('counts the items of an array and lists them', async () => {
    const { sheet, inspector } = tablePage;
    await sheet.cell(0, 'Tags').click();
    await inspector.tab('Cell').click();
    await expect(inspector.panel).toContainText('3 values');
    await expect(arrayItems(inspector.panel)).toHaveText(['x', 'y z', 'NULL']);

    await sheet.cell(1, 'Tags').click();
    await expect(inspector.panel).toContainText('0 values');
    await expect(arrayItems(inspector.panel)).toHaveCount(0);
  });
});
