import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

test.describe('an email cell', () => {
  let table: Table;
  let tablePage: TablePage;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Contacts" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Email" mathesar_types.email
       );
       INSERT INTO "Contacts" ("Email") VALUES ('ada@example.com'), (NULL);`,
    );
    table = await api.getTable(schema, 'Contacts');
    tablePage = new TablePage(page);
    await tablePage.goto(table);
  });

  test('keeps a text that is no address with the error of the database', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    const email = sheet.cell(0, 'Email');
    await email.click();
    await page.keyboard.press('Enter');
    await expect(sheet.editor).toBeFocused();
    await expect(sheet.editor).toHaveValue('ada@example.com');
    await page.keyboard.press('Control+A');
    await page.keyboard.type('ada at example');
    await page.keyboard.press('Enter');

    await expect(sheet.errorIndicator(email)).toBeVisible();
    await expect(email).toHaveText('ada at example');
    await expect(sheet.cellErrors).toContainText(
      'value for domain mathesar_types.email violates check constraint "email_check"',
    );
    expect(await storedValues(table, 'Email')).toEqual([
      'ada@example.com',
      null,
    ]);
  });

  test('a click on another cell stores the typed address', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Email').click();
    await page.keyboard.press('Enter');
    await page.keyboard.type('grace@example.org');
    await sheet.cell(0, 'Email').click();

    await expect(sheet.editor).toHaveCount(0);
    await expect(sheet.cell(1, 'Email')).toHaveText('grace@example.org');
    await expect
      .poll(() => storedValues(table, 'Email'))
      .toEqual(['ada@example.com', 'grace@example.org']);
  });
});
