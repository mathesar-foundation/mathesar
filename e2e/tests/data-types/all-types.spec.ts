import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { focusedDropdownCell } from '../../support/ui/components/typed-cells';
import { TablePage } from '../../support/ui/pages/table-page';

/** The columns of "Everything", in order, with the names of their type icons. */
const COLUMNS: [string, string[]][] = [
  ['id', ['Number']],
  ['Flag', ['Boolean']],
  ['Choice', ['Boolean']],
  ['Level', ['Enum']],
  ['Count', ['Number']],
  ['Price', []],
  ['Day', ['Date']],
  ['At', ['Time']],
  ['Stamp', ['Date & Time']],
  ['Span', ['Duration']],
  ['Name', ['Text']],
  ['Mail', ['Email']],
  ['Site', []],
  ['Code', ['UUID']],
  ['Data', ['JSON']],
  ['Tags', ['Array', 'Text']],
  ['Owner', ['User']],
  ['Host', ['Unknown column type']],
  ['List', []],
  ['Map', []],
];
const COLUMN_NAMES = COLUMNS.map(([name]) => name);

test.describe('a table with a column of every data type', () => {
  let table: Table;
  let tablePage: TablePage;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TYPE "Level" AS ENUM ('low', 'high');
       CREATE TABLE "Everything" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Flag" boolean, "Choice" boolean, "Level" "Level", "Count" integer,
         "Price" mathesar_types.mathesar_money, "Day" date, "At" time,
         "Stamp" timestamp, "Span" interval, "Name" text,
         "Mail" mathesar_types.email, "Site" mathesar_types.uri, "Code" uuid,
         "Data" jsonb, "Tags" text[], "Owner" integer, "Host" inet,
         "List" mathesar_types.mathesar_json_array,
         "Map" mathesar_types.mathesar_json_object
       );
       INSERT INTO "Everything" ("Flag", "Choice", "Level", "Count", "Price",
         "Day", "At", "Stamp", "Span", "Name", "Mail", "Site", "Code", "Data",
         "Tags", "Owner", "Host", "List", "Map")
       SELECT true, false, 'low', 7, 2.5, '2024-03-15', '13:45',
         '2024-03-15 13:45', '00:01:30', 'Ada', 'ada@example.com',
         'https://mathesar.org', '11111111-1111-1111-1111-111111111111',
         '{"a": 1}', '{x}', NULL, '10.0.0.1', '[1]', '{"k": 1}'
       FROM generate_series(1, 2);`,
    );
    table = await api.getTable(schema, 'Everything');
    await api.setColumnMetadata(table, 'Choice', { bool_input: 'dropdown' });
    await api.makeUserColumn(table, 'Owner');
    tablePage = new TablePage(page);
    await tablePage.goto(table);
  });

  test('each column header names the data type with its icon, except money, URI, JSON list and map', async () => {
    for (const [column, iconNames] of COLUMNS) {
      const icons = tablePage.sheet.columnTypeIcon(column);
      await expect(icons, column).toHaveCount(iconNames.length);
      for (const [index, iconName] of iconNames.entries()) {
        await expect(icons.nth(index), column).toHaveAccessibleName(iconName);
      }
    }
  });

  test('the arrow keys move the active cell through cells of every type', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'id').click();
    for (const column of COLUMN_NAMES.slice(1)) {
      await page.keyboard.press('ArrowRight');
      await expect(sheet.cell(0, column), column).toHaveAttribute(
        'data-cell-active',
      );
    }

    for (const column of [...COLUMN_NAMES].reverse()) {
      await page.keyboard.press('ArrowDown');
      await expect(sheet.cell(1, column), column).toHaveAttribute(
        'data-cell-active',
      );
      await page.keyboard.press('ArrowUp');
      await expect(sheet.cell(0, column), column).toHaveAttribute(
        'data-cell-active',
      );
      await page.keyboard.press('ArrowLeft');
    }
    await sheet.expectFocusOnActiveCell();
  });

  test('Tab and Shift+Tab move the active cell through cells of every type', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    await sheet.cell(0, 'id').click();
    for (const column of COLUMN_NAMES.slice(1)) {
      await page.keyboard.press('Tab');
      await expect(sheet.cell(0, column), column).toHaveAttribute(
        'data-cell-active',
      );
    }
    for (const column of [...COLUMN_NAMES].reverse().slice(1)) {
      await page.keyboard.press('Shift+Tab');
      await expect(sheet.cell(0, column), column).toHaveAttribute(
        'data-cell-active',
      );
    }
    await sheet.expectFocusOnActiveCell();
  });
});

test.describe('a long table with dropdown cells', () => {
  test('no dropdown cell takes the keyboard focus when it appears', async ({
    page,
    api,
    schema,
  }) => {
    await runSqlInSchema(
      schema,
      `CREATE TYPE "Level" AS ENUM ('low', 'high');
       CREATE TABLE "Readings" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Label" text, "Level" "Level", "Valid" boolean
       );
       INSERT INTO "Readings" ("Label", "Level", "Valid")
       SELECT 'row ' || n, 'low', true FROM generate_series(1, 200) AS n;`,
    );
    const table = await api.getTable(schema, 'Readings');
    await api.setColumnMetadata(table, 'Valid', { bool_input: 'dropdown' });
    const tablePage = new TablePage(page);
    const { sheet } = tablePage;
    await tablePage.goto(table);
    await expect(sheet.rowContaining('row 20')).toBeVisible();
    await expect(focusedDropdownCell(page)).toHaveCount(0);

    await sheet.cell(1, 'Label').click();
    await page.mouse.wheel(0, 1500);
    await expect(sheet.rowContaining('row 60')).toBeInViewport();
    await expect(focusedDropdownCell(page)).toHaveCount(0);

    await sheet.cell(sheet.rowContaining('row 60'), 'Level').click();
    await expect(focusedDropdownCell(page)).toHaveCount(1);
  });
});
