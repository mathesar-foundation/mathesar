import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { pinsKnownBug } from '../../support/known-bugs';
import { uncaughtErrorMessage } from '../../support/page-errors';
import { recordRpcCalls } from '../../support/rpc-log';
import { CellDropdown } from '../../support/ui/components/cell-dropdown';
import { cellCheckbox } from '../../support/ui/components/typed-cells';
import { ColumnFormatting } from '../../support/ui/pages/column-formatting';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

/** Where a click on a boolean cell misses its checkbox. */
const BESIDE_THE_CHECKBOX = { x: 100, y: 10 };

let table: Table;
let tablePage: TablePage;

test.beforeEach(async ({ page, api, schema }) => {
  await runSqlInSchema(
    schema,
    `CREATE TABLE "Tasks" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Done" boolean
     );
     INSERT INTO "Tasks" ("Done") VALUES (true), (false), (NULL);`,
  );
  table = await api.getTable(schema, 'Tasks');
  tablePage = new TablePage(page);
});

test.describe('a boolean cell shown as a checkbox', () => {
  test.beforeEach(async () => {
    await tablePage.goto(table);
  });

  test('is checked for true, unchecked for false and mixed for NULL', async () => {
    const { sheet } = tablePage;
    await expect(cellCheckbox(sheet.cell(0, 'Done'))).toBeChecked();
    await expect(cellCheckbox(sheet.cell(1, 'Done'))).not.toBeChecked();
    await expect(cellCheckbox(sheet.cell(1, 'Done'))).not.toBeChecked({
      indeterminate: true,
    });
    await expect(cellCheckbox(sheet.cell(2, 'Done'))).toBeChecked({
      indeterminate: true,
    });
  });

  test('a click on the checkbox of a cell that is not active stores the toggled value', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    const rpcCalls = recordRpcCalls(page);
    await cellCheckbox(sheet.cell(1, 'Done')).click();

    await expect(cellCheckbox(sheet.cell(1, 'Done'))).toBeChecked();
    await expect
      .poll(() => storedValues(table, 'Done'))
      .toEqual(['true', 'true', null]);
    expect(rpcCalls).toEqual(['records.patch']);
  });

  test('a click beside the checkbox of a cell that is not active only selects the cell', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    const rpcCalls = recordRpcCalls(page);
    await sheet.cell(1, 'Done').click({ position: BESIDE_THE_CHECKBOX });

    await expect(sheet.cell(1, 'Done')).toHaveAttribute('data-cell-active');
    await expect(cellCheckbox(sheet.cell(1, 'Done'))).not.toBeChecked();
    expect(rpcCalls).not.toContain('records.patch');
  });

  test('a click on the active cell toggles its value', async () => {
    const { sheet } = tablePage;
    await sheet.cell(1, 'Done').click({ position: BESIDE_THE_CHECKBOX });
    await sheet.cell(1, 'Done').click({ position: BESIDE_THE_CHECKBOX });

    await expect(cellCheckbox(sheet.cell(1, 'Done'))).toBeChecked();
    await expect
      .poll(() => storedValues(table, 'Done'))
      .toEqual(['true', 'true', null]);
  });

  test('Enter toggles the active cell, and NULL becomes true', async ({
    page,
  }) => {
    const { sheet } = tablePage;
    const done = sheet.cell(2, 'Done');
    await done.click({ position: BESIDE_THE_CHECKBOX });
    await page.keyboard.press('Enter');
    await expect(cellCheckbox(done)).toBeChecked();
    await expect
      .poll(() => storedValues(table, 'Done'))
      .toEqual(['true', 'false', 'true']);

    await page.keyboard.press('Enter');
    await expect(cellCheckbox(done)).not.toBeChecked();
    await expect
      .poll(() => storedValues(table, 'Done'))
      .toEqual(['true', 'false', 'false']);
    await sheet.expectFocusOnActiveCell();
  });

  test('Space does not toggle the active cell', async ({ page }) => {
    const { sheet } = tablePage;
    const done = sheet.cell(0, 'Done');
    await done.click({ position: BESIDE_THE_CHECKBOX });
    await page.keyboard.press(' ');
    await page.keyboard.press('Enter');

    await expect(cellCheckbox(done)).not.toBeChecked();
    await expect
      .poll(() => storedValues(table, 'Done'))
      .toEqual(['false', 'false', null]);
  });
});

test.describe('a boolean cell of a table without a primary key', () => {
  test.use({ allowedBrowserErrors: /Unable to update without primary key/ });

  test.beforeEach(async ({ schema }) => {
    await runSqlInSchema(
      schema,
      `ALTER TABLE "Tasks" DROP CONSTRAINT "Tasks_pkey";`,
    );
    await tablePage.goto(table);
  });

  test(
    'throws an error on Enter and keeps its value',
    pinsKnownBug('read-only-checkbox-cell-throws-on-enter'),
    async ({ page }) => {
      const { sheet } = tablePage;
      await sheet.cell(0, 'Done').click({ position: BESIDE_THE_CHECKBOX });
      const uncaughtError = page.waitForEvent('pageerror');
      await page.keyboard.press('Enter');

      expect(uncaughtErrorMessage(await uncaughtError)).toBe(
        'Unable to update without primary key',
      );
      await expect(cellCheckbox(sheet.cell(0, 'Done'))).toBeChecked();
    },
  );
});

test.describe('a read-only boolean cell', () => {
  test.fixme('ignores Enter', async ({ page, schema }) => {
    await runSqlInSchema(
      schema,
      `ALTER TABLE "Tasks" DROP CONSTRAINT "Tasks_pkey";`,
    );
    await tablePage.goto(table);
    const { sheet } = tablePage;
    await sheet.cell(0, 'Done').click({ position: BESIDE_THE_CHECKBOX });
    await page.keyboard.press('Enter');

    await expect(cellCheckbox(sheet.cell(0, 'Done'))).toBeChecked();
  });
});

test.describe('a boolean cell shown as a dropdown', () => {
  test('shows true, false and NULL as text', async ({ api }) => {
    await api.setColumnMetadata(table, 'Done', { bool_input: 'dropdown' });
    await tablePage.goto(table);
    const { sheet } = tablePage;

    await expect(sheet.cell(0, 'Done')).toHaveText('true');
    await expect(sheet.cell(1, 'Done')).toHaveText('false');
    await expect(sheet.cell(2, 'Done')).toHaveText('NULL');
  });

  test('offers NULL, true and false, and stores the chosen value', async ({
    page,
    api,
  }) => {
    await api.setColumnMetadata(table, 'Done', { bool_input: 'dropdown' });
    await tablePage.goto(table);
    const { sheet } = tablePage;
    const dropdown = new CellDropdown(page);
    await sheet.cell(0, 'Done').click();
    await page.keyboard.press('Enter');

    await expect(dropdown.options).toHaveText(['', 'true', 'false']);
    await expect(dropdown.selectedOption).toHaveText('true');
    await dropdown.option('false').click();

    await expect(dropdown.root).toHaveCount(0);
    await expect(sheet.cell(0, 'Done')).toHaveText('false');
    await expect
      .poll(() => storedValues(table, 'Done'))
      .toEqual(['false', 'false', null]);
  });

  test('custom labels name the values in the cells and in the list', async ({
    page,
    api,
  }) => {
    await api.setColumnMetadata(table, 'Done', {
      bool_input: 'dropdown',
      bool_true: 'Yes',
      bool_false: 'No',
    });
    await tablePage.goto(table);
    const { sheet } = tablePage;
    await expect(sheet.cell(0, 'Done')).toHaveText('Yes');
    await expect(sheet.cell(1, 'Done')).toHaveText('No');

    await sheet.cell(1, 'Done').click();
    await page.keyboard.press('Enter');
    await expect(new CellDropdown(page).options).toHaveText(['', 'Yes', 'No']);
  });
});

test.describe('the boolean formatting of a column', () => {
  let formatting: ColumnFormatting;

  test.beforeEach(async () => {
    formatting = new ColumnFormatting(tablePage.inspector);
    await tablePage.goto(table);
    await tablePage.sheet.columnHeader('Done').click();
  });

  test('Dropdown shows the values as text once saved', async ({ api }) => {
    const { sheet } = tablePage;
    await expect(formatting.select('Display as')).toHaveText('Checkbox');
    await formatting.choose('Display as', 'Dropdown');
    await formatting.saveButton.click();

    await expect(sheet.cell(0, 'Done')).toHaveText('true');
    await expect(cellCheckbox(sheet.cell(0, 'Done'))).toHaveCount(0);
    await expect
      .poll(() => api.columnMetadata(table, 'Done'))
      .toEqual({ bool_input: 'dropdown' });
  });

  test('custom labels are offered for the dropdown and change the cells once saved', async ({
    api,
  }) => {
    const { sheet } = tablePage;
    await expect(formatting.field('Use Custom Labels')).toHaveCount(0);
    await formatting.choose('Display as', 'Dropdown');
    await formatting.field('Use Custom Labels').check();
    await expect(formatting.field('Label for TRUE')).toHaveValue('true');
    await expect(formatting.field('Label for FALSE')).toHaveValue('false');
    await formatting.field('Label for TRUE').fill('Done');
    await formatting.field('Label for FALSE').fill('To do');
    await formatting.saveButton.click();

    await expect(sheet.cell(0, 'Done')).toHaveText('Done');
    await expect(sheet.cell(1, 'Done')).toHaveText('To do');
    await expect
      .poll(() => api.columnMetadata(table, 'Done'))
      .toEqual({
        bool_input: 'dropdown',
        bool_true: 'Done',
        bool_false: 'To do',
      });
  });

  test('an empty custom label cannot be saved', async () => {
    await formatting.choose('Display as', 'Dropdown');
    await formatting.field('Use Custom Labels').check();
    await expect(formatting.saveButton).toBeEnabled();
    await formatting.field('Label for TRUE').fill('');

    await expect(formatting.section).toContainText('This is a required field');
    await expect(formatting.saveButton).toBeDisabled();
  });
});
