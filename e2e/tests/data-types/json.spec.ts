import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

test.describe('a JSON cell', () => {
  let table: Table;
  let tablePage: TablePage;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Settings" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Raw" json,
         "Binary" jsonb,
         "List" mathesar_types.mathesar_json_array,
         "Map" mathesar_types.mathesar_json_object
       );
       INSERT INTO "Settings" ("Raw", "Binary", "List", "Map") VALUES
         ('{"a":  1}', '{"a":  1}', '[1, "a"]', '{"k": "v"}'),
         (NULL, NULL, NULL, NULL);`,
    );
    table = await api.getTable(schema, 'Settings');
    tablePage = new TablePage(page);
    await tablePage.goto(table);
  });

  test('shows json as stored, and jsonb as the database normalised it', async () => {
    const { sheet } = tablePage;
    const typed = '{"z": 1, "a": [1,   2]}';
    await expect(sheet.cell(0, 'Raw')).toHaveText('{"a":  1}');
    await expect(sheet.cell(0, 'Binary')).toHaveText('{"a": 1}');

    await sheet.editCell(sheet.cell(0, 'Raw'), typed);
    await sheet.editCell(sheet.cell(1, 'Binary'), typed);

    await expect(sheet.cell(0, 'Raw')).toHaveText(typed);
    await expect(sheet.cell(1, 'Binary')).toHaveText('{"a": [1, 2], "z": 1}');
    await expect.poll(() => storedValues(table, 'Raw')).toEqual([typed, null]);
    await expect
      .poll(() => storedValues(table, 'Binary'))
      .toEqual(['{"a": 1}', '{"a": [1, 2], "z": 1}']);
  });

  test('keeps a text that is no JSON with the error of the database', async () => {
    const { sheet } = tablePage;
    const raw = sheet.cell(0, 'Raw');
    await sheet.editCell(raw, '{"a": ');

    await expect(sheet.errorIndicator(raw)).toBeVisible();
    await expect(raw).toHaveText('{"a":');
    await expect(sheet.cellErrors).toContainText(
      'invalid input syntax for type json',
    );
    expect(await storedValues(table, 'Raw')).toEqual(['{"a":  1}', null]);
  });

  test('a list column and a map column show JSON, and the database checks its kind', async () => {
    const { sheet } = tablePage;
    const list = sheet.cell(0, 'List');
    await expect(list).toHaveText('[1, "a"]');
    await expect(sheet.cell(0, 'Map')).toHaveText('{"k": "v"}');

    await sheet.editCell(list, '{"k": "v"}');
    await expect(sheet.errorIndicator(list)).toBeVisible();
    await expect(sheet.cellErrors).toContainText(
      'value for domain mathesar_types.mathesar_json_array violates check constraint',
    );
    expect(await storedValues(table, 'List')).toEqual(['[1, "a"]', null]);
  });
});
