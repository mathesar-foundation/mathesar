import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { expect, test } from '../../support/fixtures';
import { TablePage } from '../../support/ui/pages/table-page';
import { storedValues } from './stored-values';

test.describe('a UUID cell', () => {
  let table: Table;
  let tablePage: TablePage;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Devices" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Serial" uuid
       );
       INSERT INTO "Devices" ("Serial") VALUES
         ('11111111-1111-1111-1111-111111111111');`,
    );
    table = await api.getTable(schema, 'Devices');
    tablePage = new TablePage(page);
    await tablePage.goto(table);
  });

  test('shows a typed UUID as the database stored it, in lower case', async () => {
    const { sheet } = tablePage;
    await sheet.editCell(
      sheet.cell(0, 'Serial'),
      'A0EEBC99-9C0B-4EF8-BB6D-6BB9BD380A11',
    );

    await expect(sheet.cell(0, 'Serial')).toHaveText(
      'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11',
    );
    await expect
      .poll(() => storedValues(table, 'Serial'))
      .toEqual(['a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11']);
  });

  test('keeps a text that is no UUID with the error of the database', async () => {
    const { sheet } = tablePage;
    const serial = sheet.cell(0, 'Serial');
    await sheet.editCell(serial, 'not-a-uuid');

    await expect(sheet.errorIndicator(serial)).toBeVisible();
    await expect(serial).toHaveText('not-a-uuid');
    await expect(sheet.cellErrors).toContainText(
      'invalid input syntax for type uuid: "not-a-uuid"',
    );
    expect(await storedValues(table, 'Serial')).toEqual([
      '11111111-1111-1111-1111-111111111111',
    ]);
  });
});
