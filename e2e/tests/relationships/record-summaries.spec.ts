import { runSqlInSchema } from '../../support/api/mathesar';
import { failRpcMethod } from '../../support/rpc-failures';
import { chooseColumn } from '../../support/ui/components/column-options';
import { menuItem } from '../../support/ui/components/menu';
import { Toasts } from '../../support/ui/components/toast';
import { RecordSummaryEditor } from '../../support/ui/pages/record-summary-editor';
import { TablePage } from '../../support/ui/pages/table-page';
import { expect, test } from './library';

test('the default record summary is the first text column, or the first column of a table without one', async ({
  page,
  schema,
  library,
}) => {
  await runSqlInSchema(
    schema,
    `CREATE TABLE "Editions" (
       "Year" integer,
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY
     );
     INSERT INTO "Editions" ("Year") VALUES (1965), (1990);
     ALTER TABLE "Books" ADD COLUMN "Edition" integer REFERENCES "Editions" (id);
     UPDATE "Books" SET "Edition" = 2 WHERE id = 1;`,
  );
  const tablePage = new TablePage(page);
  await tablePage.goto(library.books);

  await expect(tablePage.sheet.cell(0, 'Author')).toHaveText('Frank Herbert');
  await expect(tablePage.sheet.cell(0, 'Edition')).toHaveText('1990');
});

test.describe('the record summary of a table', () => {
  let tablePage: TablePage;
  let editor: RecordSummaryEditor;

  test.beforeEach(async ({ page, library }) => {
    tablePage = new TablePage(page);
    editor = new RecordSummaryEditor(page);
    await tablePage.goto(library.authors);
    await tablePage.inspector.button('Record Summary').click();
  });

  test('starts from the first text column when customized and previews the selected record', async () => {
    await expect(editor.useDefault).toBeChecked();
    await expect(editor.saveButton).toHaveCount(0);
    await editor.customizeFields.check();

    await expect(editor.parts).toHaveCount(1);
    await expect(editor.part(0).columnSelects).toHaveText(['Name']);
    await expect(editor.preview).toHaveText('Frank Herbert');
    await tablePage.sheet.cell(2, 'Country').click();
    await expect(editor.preview).toHaveText('James Joyce');
  });

  test('takes a column of the linked table for a column that links to it', async ({
    page,
    api,
    library,
  }) => {
    await editor.customizeFields.check();
    await editor.addFieldButton.click();
    await menuItem(page, 'Column').click();
    await chooseColumn(editor.part(1).columnSelects.first(), 'Agent');
    await expect(editor.part(1).columnSelects).toHaveText(['Agent', '']);
    await chooseColumn(editor.part(1).columnSelects.last(), 'City');
    await expect(editor.part(1).columnSelects).toHaveText(['Agent', 'City']);

    await expect(editor.preview).toHaveText('Frank HerbertNew York');
    await editor.saveButton.click();
    await expect(editor.saveButton).toHaveCount(0);
    expect(await api.recordSummaryTemplate(library.authors)).toEqual([
      [2],
      [4, 3],
    ]);
  });

  test('takes its parts in the order they are dragged to', async ({
    page,
    api,
    library,
  }) => {
    await editor.customizeFields.check();
    await editor.addFieldButton.click();
    await menuItem(page, 'Column').click();
    await chooseColumn(editor.part(1).columnSelects.first(), 'Country');
    await expect(editor.preview).toHaveText('Frank HerbertUSA');
    await editor.dragPart(1, 0);

    await expect(editor.part(0).columnSelects).toHaveText(['Country']);
    await expect(editor.preview).toHaveText('USAFrank Herbert');
    await editor.saveButton.click();
    await expect(editor.saveButton).toHaveCount(0);
    expect(await api.recordSummaryTemplate(library.authors)).toEqual([
      [3],
      [2],
    ]);
  });

  test('needs at least one column', async ({ page }) => {
    await editor.customizeFields.check();
    await editor.part(0).deleteButton.click();
    await expect(editor.noPartsNote).toBeVisible();

    await editor.addFieldButton.click();
    await menuItem(page, 'Text').click();
    await editor.part(0).text.fill('Someone');
    await expect(editor.error).toHaveText(
      'Record summary cannot be static. Add at least one column field in order to save.',
    );
    await expect(editor.saveButton).toBeDisabled();
  });

  test('keeps the changes and shows the error when they cannot be saved', async ({
    page,
    api,
    library,
  }) => {
    await failRpcMethod(page, 'tables.metadata.set', 'The template is refused');
    await editor.customizeFields.check();
    await editor.saveButton.click();

    await new Toasts(page).expectMessage(
      /Unable to save changes[\s\S]*The template is refused/,
    );
    await expect(editor.customizeFields).toBeChecked();
    await expect(editor.saveButton).toBeEnabled();
    expect(await api.recordSummaryTemplate(library.authors)).toBeNull();
  });

  test('Reset drops the changes', async ({ page, api, library }) => {
    await editor.customizeFields.check();
    await editor.addFieldButton.click();
    await menuItem(page, 'Text').click();
    await editor.resetButton.click();

    await expect(editor.useDefault).toBeChecked();
    await expect(editor.parts).toHaveCount(0);
    await expect(editor.saveButton).toHaveCount(0);
    expect(await api.recordSummaryTemplate(library.authors)).toBeNull();
  });
});

test.describe('the summary of a linked table, in the Column tab of a linking column', () => {
  let tablePage: TablePage;
  let editor: RecordSummaryEditor;

  test.beforeEach(({ page }) => {
    tablePage = new TablePage(page);
    editor = new RecordSummaryEditor(page);
  });

  test('changes the linked cells at once when saved', async ({
    page,
    api,
    library,
  }) => {
    await tablePage.goto(library.books);
    await tablePage.sheet.columnHeader('Author').click();
    await tablePage.inspector.button('Linked Record Summary').click();
    await expect(editor.root).toContainText(
      'Configure Authors record summaries here.',
    );
    await editor.customizeFields.check();
    await editor.addFieldButton.click();
    await menuItem(page, 'Text').click();
    await editor.part(1).text.fill(' of ');
    await editor.addFieldButton.click();
    await menuItem(page, 'Column').click();
    await chooseColumn(editor.part(2).columnSelects.first(), 'Country');
    await expect(editor.preview).toHaveText('Frank Herbert of USA');
    await editor.saveButton.click();

    await expect(tablePage.sheet.cell(0, 'Author')).toHaveText(
      'Frank Herbert of USA',
    );
    await expect(tablePage.sheet.cell(1, 'Author')).toHaveText(
      'Jane Austen of UK',
    );
    expect(await api.recordSummaryTemplate(library.authors)).toEqual([
      [2],
      ' of ',
      [3],
    ]);
  });

  test('"Use Default" brings back the default summary once saved', async ({
    api,
    library,
  }) => {
    await api.setRecordSummaryTemplate(library.authors, [[3]]);
    await tablePage.goto(library.books);
    await expect(tablePage.sheet.cell(0, 'Author')).toHaveText('USA');
    await tablePage.sheet.columnHeader('Author').click();
    await tablePage.inspector.button('Linked Record Summary').click();
    await expect(editor.customizeFields).toBeChecked();
    await editor.useDefault.check();
    await editor.saveButton.click();

    await expect(tablePage.sheet.cell(0, 'Author')).toHaveText('Frank Herbert');
    expect(await api.recordSummaryTemplate(library.authors)).toBeNull();
  });
});

test('a table without a primary key has no record summary to configure', async ({
  page,
  api,
  schema,
}) => {
  await runSqlInSchema(schema, `CREATE TABLE "Notes" ("Text" text)`);
  const tablePage = new TablePage(page);
  await tablePage.goto(await api.getTable(schema, 'Notes'));
  await tablePage.inspector.button('Record Summary').click();

  await expect(new RecordSummaryEditor(page).error).toHaveText(
    "The Notes table's record summaries cannot be configured because it does not have a primary key column.",
  );
});

test('a part whose column was dropped reads "Deleted column" and adds nothing to the summary', async ({
  page,
  api,
  schema,
  library,
}) => {
  await api.setRecordSummaryTemplate(library.authors, [[2], ' from ', [3]]);
  await runSqlInSchema(schema, 'ALTER TABLE "Authors" DROP COLUMN "Country"');
  const tablePage = new TablePage(page);
  const editor = new RecordSummaryEditor(page);
  await tablePage.goto(library.authors);
  await tablePage.inspector.button('Record Summary').click();

  await expect(editor.customizeFields).toBeChecked();
  await expect(editor.part(0).columnSelects).toHaveText(['Name']);
  await expect(editor.part(1).text).toHaveValue(' from ');
  await expect(editor.part(2).root).toHaveText('Deleted column');
  await expect(editor.part(2).columnSelects).toHaveCount(0);
  await expect(editor.preview).toHaveText('Frank Herbert from');
});
