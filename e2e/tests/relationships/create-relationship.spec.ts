import { runSqlInSchema } from '../../support/api/mathesar';
import { chooseOption } from '../../support/ui/components/select';
import { Toasts } from '../../support/ui/components/toast';
import { ExtendDropdown } from '../../support/ui/pages/extend-dropdown';
import {
  CreateRelationshipModal,
  TableRelationships,
} from '../../support/ui/pages/table-relationships';
import { TablePage } from '../../support/ui/pages/table-page';
import { tableUrl } from '../../support/ui/urls';
import { expect, foreignKeys, test } from './library';

test.describe('the relationships of a table in the inspector', () => {
  test('are the tables it references and the tables that reference it, as links', async ({
    page,
    library,
  }) => {
    const relationships = new TableRelationships(page);
    await new TablePage(page).goto(library.books);

    await expect(relationships.referencesFromThisTable).toHaveText([
      'Authors Referenced via Books Author',
      'Publishers Referenced via Books Publisher',
    ]);
    await expect(relationships.referencesFromThisTable.first()).toHaveAttribute(
      'href',
      tableUrl(library.authors),
    );
    await expect(relationships.referencesToThisTable).toHaveText([
      'Books_Tags Book references Books',
    ]);
  });

  test('are missing for a table without links', async ({
    page,
    api,
    schema,
  }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Shelves" (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY)`,
    );
    const relationships = new TableRelationships(page);
    await new TablePage(page).goto(await api.getTable(schema, 'Shelves'));

    await expect(relationships.emptyNote).toBeVisible();
    await expect(relationships.referencesFromThisTable).toHaveCount(0);
    await expect(relationships.createButton).toBeVisible();
  });
});

test.describe('the Create Relationship form', () => {
  let tablePage: TablePage;
  let relationships: TableRelationships;
  let form: CreateRelationshipModal;

  test.beforeEach(async ({ page, library }) => {
    tablePage = new TablePage(page);
    relationships = new TableRelationships(page);
    form = new CreateRelationshipModal(page);
    await tablePage.goto(library.tags);
    await relationships.createButton.click();
    await expect(form.targetTable).toBeFocused();
  });

  test('links many records to one record of the other table with a new column here', async ({
    page,
    schema,
  }) => {
    await chooseOption(form.targetTable, 'Publishers');
    await expect(form.type('Many to One')).toBeChecked();
    await form
      .change("We'll add a column in Tags which references Publishers")
      .click();
    await expect(form.columnName).toHaveValue('Publisher');
    await form.submitButton.click();

    await new Toasts(page).expectMessage(
      'The link has been created successfully',
    );
    await form.expectClosed();
    await expect(tablePage.sheet.columnHeader('Publisher')).toBeVisible();
    await expect(relationships.referencesFromThisTable).toHaveText([
      'Publishers Referenced via Tags Publisher',
    ]);
    expect(await foreignKeys(schema)).toContainEqual({
      name: 'Tags_Publisher_fkey',
      from: 'Tags.Publisher',
      to: 'Publishers.id',
    });
  });

  test('links one record to many records of the other table with a new column there', async ({
    schema,
  }) => {
    await chooseOption(form.targetTable, 'Books');
    await form.type('One to Many').check();
    await form
      .change("We'll add a column in Books which references Tags")
      .click();
    await expect(form.columnName).toHaveValue('Tag');
    await form.submitButton.click();

    await form.expectClosed();
    await expect(relationships.referencesToThisTable).toHaveText([
      'Books_Tags Tag references Tags',
      'Books Tag references Tags',
    ]);
    expect(await foreignKeys(schema)).toContainEqual({
      name: 'Books_Tag_fkey',
      from: 'Books.Tag',
      to: 'Tags.id',
    });
  });

  test('links many records to many through a new mapping table, which "Extend" then offers', async ({
    page,
    schema,
  }) => {
    await chooseOption(form.targetTable, 'Authors');
    await form.type('Many to Many').check();
    await form.change("We'll create a new table Tags_Authors").click();
    await expect(form.mappingTableName).toHaveValue('Tags_Authors');
    await form.mappingTableName.fill('Fans');
    await expect(form.change(/We'll add a column in Fans/)).toHaveCount(2);
    await form.submitButton.click();

    await form.expectClosed();
    expect(await foreignKeys(schema)).toEqual(
      expect.arrayContaining([
        { name: 'Fans_Author_fkey', from: 'Fans.Author', to: 'Authors.id' },
        { name: 'Fans_Tag_fkey', from: 'Fans.Tag', to: 'Tags.id' },
      ]),
    );
    const extend = new ExtendDropdown(page);
    await extend.trigger.click();
    await expect(extend.relatedTable('Authors via Fans')).toBeVisible();
  });

  test('links a table to itself, but not one to many, through two columns of different names', async ({
    schema,
  }) => {
    await chooseOption(form.targetTable, 'Tags');
    await expect(form.types).toHaveCount(2);
    await expect(form.type('One to Many')).toHaveCount(0);
    await form.type('Many to Many').check();
    await form
      .change("We'll add two columns in Tags_Tags each referencing Tags")
      .click();
    await expect(form.mappingColumnNames.nth(0)).toHaveValue('Tag_1');
    await expect(form.mappingColumnNames.nth(1)).toHaveValue('Tag_2');

    await form.mappingColumnNames.nth(1).fill('Tag_1');
    await expect(form.body).toContainText(
      'The two columns cannot have the same name.',
    );
    await expect(form.submitButton).toBeDisabled();

    await form.mappingColumnNames.nth(1).fill('Related');
    await form.submitButton.click();
    await form.expectClosed();
    await expect(relationships.referencesToThisTable).toHaveText([
      'Books_Tags Tag references Tags',
      'Tags_Tags Tag_1 references Tags',
      'Tags_Tags Related references Tags',
    ]);
    expect(await foreignKeys(schema)).toEqual(
      expect.arrayContaining([
        {
          name: 'Tags_Tags_Tag_1_fkey',
          from: 'Tags_Tags.Tag_1',
          to: 'Tags.id',
        },
        {
          name: 'Tags_Tags_Related_fkey',
          from: 'Tags_Tags.Related',
          to: 'Tags.id',
        },
      ]),
    );
  });

  test('refuses a column name that is empty or taken and a table name that is taken or "id"', async () => {
    await chooseOption(form.targetTable, 'Publishers');
    await form.change(/We'll add a column in Tags/).click();
    await form.columnName.fill('');
    await expect(form.body).toContainText('Value cannot be empty.');
    await form.columnName.fill('Label');
    await expect(form.body).toContainText(
      'A column with that name already exists',
    );
    await expect(form.submitButton).toBeDisabled();

    await form.type('Many to Many').check();
    await form.change(/We'll create a new table/).click();
    await form.mappingTableName.fill('Books');
    await expect(form.body).toContainText(
      'A table with that name already exists.',
    );
    await form.mappingTableName.fill('Tags_Publishers');
    await form
      .change(/We'll add a column in Tags_Publishers which references Tags/)
      .click();
    await form.mappingColumnNames.first().fill('id');
    await expect(form.body).toContainText(
      'The name "id" is reserved for the primary key column that will be created when creating the table.',
    );
    await expect(form.submitButton).toBeDisabled();
  });

  test('choosing another table resets the kind of relationship', async () => {
    await chooseOption(form.targetTable, 'Publishers');
    await form.type('One to Many').check();
    await chooseOption(form.targetTable, 'Books');

    await expect(form.type('Many to One')).toBeChecked();
  });

  test('ignores Escape, creates nothing on Cancel and starts empty next time', async ({
    page,
    schema,
  }) => {
    await chooseOption(form.targetTable, 'Publishers');
    await page.keyboard.press('Escape');
    await form.expectOpen();
    await form.cancelButton.click();

    await form.expectClosed();
    await relationships.createButton.click();
    await expect(form.targetTable).toHaveText('Select Table');
    await expect(form.submitButton).toBeDisabled();
    expect(await foreignKeys(schema)).toHaveLength(5);
  });

  test('shows the database error and stays open when the other table has no primary key', async ({
    page,
    schema,
  }) => {
    await runSqlInSchema(schema, `CREATE TABLE "Notes" ("Text" text)`);
    await page.reload();
    await tablePage.expectLoaded();
    await relationships.createButton.click();
    await chooseOption(form.targetTable, 'Notes');
    await form.submitButton.click();

    await new Toasts(page).expectMessage(
      /there is no primary key for referenced table/,
    );
    await form.expectOpen();
    expect(await foreignKeys(schema)).toHaveLength(5);
  });
});

test('the Create Relationship form suggests names that are not taken yet', async ({
  page,
  library,
}) => {
  const form = new CreateRelationshipModal(page);
  await new TablePage(page).goto(library.books);
  await new TableRelationships(page).createButton.click();
  await chooseOption(form.targetTable, 'Authors');
  await form.change(/We'll add a column in Books/).click();
  await expect(form.columnName).toHaveValue('Author_1');

  await chooseOption(form.targetTable, 'Tags');
  await form.type('Many to Many').check();
  await form.change(/We'll create a new table/).click();
  await expect(form.mappingTableName).toHaveValue('Books_Tags_1');
});
