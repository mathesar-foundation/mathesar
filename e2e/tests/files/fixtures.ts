/** The "Attachment" cell of a row of the sheet. */
export function attachmentCell(sheet: Sheet, row: number): FileField {
  return new FileField(sheet.cell(row, 'Attachment'));
}

/** The storage URI that a file uploaded through the UI gets. It holds the time of the upload. */
export function uploadedUri(fileName: string, user = 'admin'): RegExp {
  const escapedName = fileName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(
    `^s3://mathesar-e2e/${user}/\\d{8}-\\d{12}/${escapedName}$`,
  );
}

/** What a cell holds after a file was uploaded through the UI. */
export function uploadedFile(fileName: string, user = 'admin'): unknown {
  return {
    uri: expect.stringMatching(uploadedUri(fileName, user)),
    mash: expect.stringMatching(/^[0-9a-f]{64}$/),
  };
}

/** A file reference as PostgreSQL prints the jsonb value that holds it. */
export function jsonbText({ uri, mash }: StoredFile): string {
  return `{"uri": "${uri}", "mash": "${mash}"}`;
}

/** Writes a value into "Attachment" of a record of "Documents", as JSON text. */
export async function storeAttachment(
  table: Table,
  id: number,
  json: string,
): Promise<void> {
  await runSql(
    table.schema.database.name,
    `UPDATE ${quoteIdentifier(table.schema.name)}."Documents"
     SET "Attachment" = $1 WHERE id = $2`,
    [json, id],
  );
}

/** The values of "Attachment" in the order of "id". */
export async function storedAttachments(table: Table): Promise<unknown[]> {
  const rows = await runSqlInSchema<{ value: unknown }>(
    table.schema,
    'SELECT "Attachment" AS value FROM "Documents" ORDER BY id',
  );
  return rows.map(({ value }) => value);
}

