import { runSqlInSchema } from '../../support/api/mathesar';
import { ColumnInspector } from '../../support/ui/pages/column-inspector';
import { TablePage } from '../../support/ui/pages/table-page';
import { expect, test } from './fixtures';

test.describe('the Column tab with several columns', () => {
  test.use({
    extraSql: `CREATE TABLE "Authors" (
                 id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                 "Name" text
               );
               ALTER TABLE "Books" ADD COLUMN "Writer" integer REFERENCES "Authors" (id);`,
  });

  test('offers only the actions that work on all selected columns', async ({
    tablePage: { sheet },
    columnInspector,
  }) => {
    await sheet.columnHeader('Title').click();
    await sheet.columnHeader('Pages').click({ modifiers: ['Shift'] });

    await expect(columnInspector.selectionCount).toHaveText(
      '3 columns selected',
    );
    await expect(columnInspector.sectionHeaders).toHaveText(['Actions']);
    await expect(columnInspector.extractButton).toHaveText(
      'Extract Columns Into a New Table',
    );
    await expect(columnInspector.moveButton).toHaveText(
      'Move Columns To Linked Table',
    );
    await expect(columnInspector.deleteButton).toHaveCount(0);
  });

  test('a range of cells counts the columns it spans', async ({
    tablePage: { sheet, inspector },
    columnInspector,
  }) => {
    await sheet.cell(0, 'Author').click();
    await sheet.cell(1, 'Code').click({ modifiers: ['Shift'] });
    await inspector.tab('Column').click();

    await expect(columnInspector.selectionCount).toHaveText(
      '3 columns selected',
    );
  });
});

test('the Column tab of a table without records asks for a selection', async ({
  page,
  api,
  schema,
}) => {
  await runSqlInSchema(
    schema,
    'CREATE TABLE "Empty" (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "Name" text)',
  );
  const tablePage = new TablePage(page);
  await tablePage.goto(await api.getTable(schema, 'Empty'));
  await tablePage.inspector.tab('Column').click();

  await expect(
    new ColumnInspector(page, tablePage.inspector).noSelectionNote,
  ).toBeVisible();
});
