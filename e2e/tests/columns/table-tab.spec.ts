import { runSqlInSchema } from '../../support/api/mathesar';
import { env } from '../../support/env';
import { pinsKnownBug } from '../../support/known-bugs';
import { recordRpcCalls } from '../../support/rpc-log';
import { chooseOption } from '../../support/ui/components/select';
import { Toasts } from '../../support/ui/components/toast';
import { schemaUrl, tableUrl } from '../../support/ui/urls';
import { expect, storedTables, test, trackedColumnAttnum } from './fixtures';

test.describe('the name of the table', () => {
  test.use({
    extraSql: `CREATE TABLE "Authors" (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY)`,
  });

  test('renames the table in the heading, the page title and PostgreSQL', async ({
    page,
    books,
    tablePage,
    tableTab: { name },
  }) => {
    await name.input.click();
    await expect(name.input).toBeFocused();
    await page.keyboard.press('ControlOrMeta+A');
    await page.keyboard.type('Novels');
    await name.saveButton.click();

    await expect(tablePage.heading).toHaveText('Novels');
    await expect(page).toHaveTitle('Novels | Mathesar');
    await expect(name.saveButton).toHaveCount(0);
    await expect(name.input).toHaveValue('Novels');
    await expect(page).toHaveURL(tableUrl(books));
    expect((await storedTables(books.schema)).map(({ name }) => name)).toEqual([
      'Authors',
      'Novels',
    ]);
  });

  test('rejects an empty name and the name of another table', async ({
    tableTab: { name },
  }) => {
    await name.input.click();
    await name.input.fill('Authors');
    await expect(name.errors).toHaveText(
      'A table with that name already exists.',
    );
    await expect(name.saveButton).toBeDisabled();

    await name.input.fill('  ');
    await expect(name.errors).toHaveText('The table name cannot be empty.');
    await expect(name.saveButton).toBeDisabled();

    await name.input.fill('authors');
    await expect(name.errors).toHaveCount(0);
    await expect(name.saveButton).toBeEnabled();
  });
});

test.describe('the description of the table', () => {
  test('saves a description of several lines', async ({
    page,
    books,
    tableTab: { description },
  }) => {
    await description.input.click();
    await page.keyboard.type('Long reads');
    await page.keyboard.press('Enter');
    await page.keyboard.type('for the summer');
    await description.saveButton.click();

    await expect(description.saveButton).toHaveCount(0);
    await expect(description.input).toHaveValue('Long reads\nfor the summer');
    expect(await storedTables(books.schema)).toEqual([
      { name: 'Books', description: 'Long reads\nfor the summer' },
    ]);
  });

  test.describe('that is stored', () => {
    test.use({ extraSql: `COMMENT ON TABLE "Books" IS 'Novels'` });

    test(
      'emptied, is not saved and an error is shown',
      pinsKnownBug('table-description-cannot-be-cleared'),
      async ({ page, books, tableTab: { description } }) => {
        await expect(description.input).toHaveValue('Novels');
        await description.input.click();
        await description.input.fill('');
        await description.saveButton.click();

        await new Toasts(page).expectMessage(
          'There must be atleast one request',
        );
        await expect(description.saveButton).toBeVisible();
        expect(await storedTables(books.schema)).toEqual([
          { name: 'Books', description: 'Novels' },
        ]);
      },
    );

    test.fixme('emptied, is removed', async ({
      books,
      tableTab: { description },
    }) => {
      await description.input.click();
      await description.input.fill('');
      await description.saveButton.click();

      await expect(description.saveButton).toHaveCount(0);
      expect(await storedTables(books.schema)).toEqual([
        { name: 'Books', description: null },
      ]);
    });
  });
});

test.describe('Delete Table', () => {
  test('deletes the table once its name is typed, and opens the schema page', async ({
    page,
    books,
    tableTab,
  }) => {
    await tableTab.deleteButton.click();
    await expect(tableTab.deleteModal.tableName).toBeFocused();
    await expect(tableTab.deleteModal.button('Delete Table')).toBeDisabled();
    await tableTab.deleteModal.tableName.fill('Books');
    await tableTab.deleteModal.button('Delete Table').click();

    await expect(page).toHaveURL(schemaUrl(books.schema));
    expect(await storedTables(books.schema)).toEqual([]);
  });

  test.describe('of a table that a view uses', () => {
    test.use({
      extraSql: 'CREATE VIEW "Titles" AS SELECT "Title" FROM "Books"',
    });

    test('is refused with the error of the database, and the page stays', async ({
      page,
      books,
      tablePage,
      tableTab,
    }) => {
      await tableTab.deleteButton.click();
      await tableTab.deleteModal.tableName.fill('Books');
      await tableTab.deleteModal.button('Delete Table').click();

      await new Toasts(page).expectMessage(
        'Unable to delete Table. DependentObjectsStillExist: cannot drop table',
      );
      await tableTab.deleteModal.expectClosed();
      await expect(page).toHaveURL(tableUrl(books));
      await expect(tablePage.sheet.recordRows).toHaveCount(5);
      expect(
        (await storedTables(books.schema)).map(({ name }) => name),
      ).toEqual(['Books']);
    });
  });
});

test.describe('Last Editor Tracking', () => {
  test('explains that it needs a User column', async ({ tableTab }) => {
    await tableTab.userTracking.header.click();

    await expect(tableTab.noUserColumnNote).toBeVisible();
    await expect(tableTab.trackedColumn).toHaveCount(0);
  });

  test.describe('of a table with User columns', () => {
    test.use({
      extraSql: `ALTER TABLE "Books" ADD COLUMN "Editor" integer, ADD COLUMN "Checker" integer`,
    });

    test.beforeEach(async ({ api, books }) => {
      await api.makeUserColumn(books, 'Editor');
      await api.makeUserColumn(books, 'Checker');
    });

    test('stores the chosen column', async ({ api, books, tableTab }) => {
      await tableTab.userTracking.header.click();
      await expect(tableTab.trackedColumn).toHaveText('None');
      await chooseOption(tableTab.trackedColumn, 'Editor');

      await expect(tableTab.trackedColumn).toHaveText('Editor');
      await expect
        .poll(() => trackedColumnAttnum(api, books))
        .toBe(books.columns.Editor);
    });

    test('choosing the tracked column reloads the sheet and clears its selection', async ({
      page,
      tablePage: { sheet },
      tableTab,
    }) => {
      await expect(sheet.activeCell).toHaveCount(1);
      await expect(sheet.selectedCells).toHaveCount(1);
      await tableTab.userTracking.header.click();
      const rpcCalls = recordRpcCalls(page);
      await chooseOption(tableTab.trackedColumn, 'Editor');

      await expect(sheet.activeCell).toHaveCount(0);
      await expect(sheet.selectedCells).toHaveCount(0);
      await expect.poll(() => rpcCalls).toContain('records.list');
    });

    test.describe('that tracks one of them', () => {
      let rpcCalls: string[];

      test.beforeEach(async ({ page, api, books }) => {
        await api.trackEditingUserIn(books, 'Editor');
        rpcCalls = recordRpcCalls(page);
      });

      test('the tracked column records who edits a record', async ({
        api,
        books,
        tablePage: { sheet },
      }) => {
        await sheet.editCell(sheet.cell(0, 'Title'), 'Dune Messiah');

        await expect(sheet.cell(0, 'Editor')).toHaveText(env.admin.username);
        await expect(sheet.cell(0, 'Checker')).toHaveText('NULL');
        const admin = await api.findUser(env.admin.username);
        expect(
          await runSqlInSchema(
            books.schema,
            `SELECT "Editor", "Checker" FROM "Books" WHERE "Title" = 'Dune Messiah'`,
          ),
        ).toEqual([{ Editor: admin?.id, Checker: null }]);
      });

      test('shows the tracked column without storing anything when it opens', async ({
        api,
        books,
        tableTab,
      }) => {
        await tableTab.userTracking.header.click();

        await expect(tableTab.trackedColumn).toHaveText('Editor');
        expect(rpcCalls).not.toContain('tables.metadata.set');
        expect(await trackedColumnAttnum(api, books)).toBe(
          books.columns.Editor,
        );
      });

      test('the cells of the tracked column cannot be edited', async ({
        page,
        tablePage: { sheet },
      }) => {
        await sheet.cell(0, 'Title').dblclick();
        await expect(sheet.editor).toBeVisible();
        await page.keyboard.press('Escape');
        await sheet.cell(0, 'Editor').dblclick();

        await expect(sheet.editor).toHaveCount(0);
      });

      test('"None" stops the tracking', async ({ api, books, tableTab }) => {
        await tableTab.userTracking.header.click();
        await chooseOption(tableTab.trackedColumn, 'None');

        await expect(tableTab.trackedColumn).toHaveText('None');
        await expect.poll(() => trackedColumnAttnum(api, books)).toBeNull();
      });
    });
  });
});
