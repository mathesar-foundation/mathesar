/** Authors and the books they wrote, the same in every run. */
export interface Library {
  schema: Schema;
  authors: Table;
  books: Table;
}

interface VisualFixtures {
  /** `database`, seeded by `seedLibrary`. */
  library: Library;
  /**
   * Creates a database for a page that shows its name. The name must be the
   * same in every run and differ from that of every other test.
   */
  createNamedDatabase: (name: string) => Promise<Database>;
  /** Creates a user for a page that shows the username. */
  createNamedUser: (newUser: NewUser & { username: string }) => Promise<User>;
}

interface RpcCall {
  id: number;
  method: string;
}

interface RpcAnswer {
  id: number;
  result?: unknown;
}

/**
 * Changes what an RPC method answers to the page. Tests of other areas change
 * the users, the roles and the settings of the instance at the same time.
 */
export async function rewriteRpcResult<Result>(
  page: Page,
  method: string,
  rewrite: (result: Result) => Result,
): Promise<void> {
  await page.route('**/api/rpc/v0/', async (route) => {
    const body = route.request().postDataJSON() as RpcCall | RpcCall[];
    const ids = [body]
      .flat()
      .filter((call) => call.method === method)
      .map(({ id }) => id);
    if (ids.length === 0) {
      await route.fallback();
      return;
    }
    const response = await route.fetch();
    const answers = (await response.json()) as RpcAnswer | RpcAnswer[];
    const rewritten = [answers]
      .flat()
      .map((answer) =>
        ids.includes(answer.id) && 'result' in answer
          ? { ...answer, result: rewrite(answer.result as Result) }
          : answer,
      );
    await route.fulfill({
      response,
      json: Array.isArray(answers) ? rewritten : rewritten[0],
    });
  });
}

/**
 * Adds the schema "Catalog" with "Authors" (3 records) and "Books" (5 records,
 * which refer to them) to a database, and names the database "Library".
 */
export async function seedLibrary(
  api: MathesarApi,
  database: Database,
): Promise<Library> {
  await api.setNickname(database, 'Library');
  const schema = await api.createSchema(database, 'Catalog');
  await runSqlInSchema(
    schema,
    `COMMENT ON SCHEMA "Catalog" IS 'Books and the people who wrote them';
     CREATE TYPE "Genre" AS ENUM ('Fiction', 'Poetry', 'Science');
     CREATE TABLE "Authors" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Name" text NOT NULL,
       "Country" text
     );
     INSERT INTO "Authors" ("Name", "Country") VALUES
       ('Frank Herbert', 'USA'), ('Jane Austen', 'England'),
       ('James Joyce', 'Ireland');
     CREATE TABLE "Books" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Title" text NOT NULL,
       "Author" integer REFERENCES "Authors" (id),
       "Genre" "Genre",
       "Published" date,
       "Pages" integer,
       "Available" boolean
     );
     INSERT INTO "Books"
       ("Title", "Author", "Genre", "Published", "Pages", "Available")
     VALUES
       ('Dune', 1, 'Fiction', '1965-08-01', 412, true),
       ('Emma', 2, 'Fiction', '1815-12-23', 474, false),
       ('Ulysses', 3, 'Fiction', '1922-02-02', 730, true),
       ('Pride and Prejudice', 2, 'Fiction', '1813-01-28', 432, true),
       ('Leaves of Grass', NULL, 'Poetry', NULL, NULL, NULL);`,
  );
  return {
    schema,
    authors: await api.getTable(schema, 'Authors'),
    books: await api.getTable(schema, 'Books'),
  };
}

/** Resolves once no part of the page loads any more, so that a screenshot shows it at rest. */
export async function expectSettled(page: Page): Promise<void> {
  // A file cell holds a hidden spinner that shows while the full file loads.
  const spinners = new AppShell(page).spinners.filter({ visible: true });
  await expect(spinners).toHaveCount(0);
}

export const test = base.extend<VisualFixtures>({
  library: async ({ api, database }, use) => {
    await use(await seedLibrary(api, database));
  },

  createNamedDatabase: async ({ api, pendingCleanups }, use) => {
    const databases: Database[] = [];
    await use(async (name) => {
      // An interrupted run leaves its databases behind.
      await api.dropDatabaseNamed(name);
      const database = await api.createDatabase(name);
      databases.push(database);
      return database;
    });
    for (const database of databases) {
      pendingCleanups.push((admin) => admin.dropDatabase(database));
    }
  },

  createNamedUser: async ({ api, createUser }, use) => {
    await use(async (newUser) => {
      // An interrupted run leaves its users behind.
      await api.deleteUserNamed(newUser.username);
      return createUser(newUser);
    });
  },
});

