import path from 'node:path';

import type { Locator } from '@playwright/test';

import { uploadFile } from '../../support/api/file-uploads';
import { runSqlInSchema } from '../../support/api/mathesar';
import { quoteIdentifier, runSql } from '../../support/api/postgres';
import { env } from '../../support/env';
import { DateTimePicker } from '../../support/ui/components/date-time-picker';
import { FileField } from '../../support/ui/components/file-attachments';
import { menuItem } from '../../support/ui/components/menu';
import { Modal } from '../../support/ui/components/modal';
import { TablePage } from '../../support/ui/pages/table-page';
import { TableRelationships } from '../../support/ui/pages/table-relationships';
