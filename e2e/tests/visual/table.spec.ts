import { expect, expectSettled, test } from './fixtures';

test.describe('a table with a column of every data type', () => {
  // Wide enough to show all columns next to each other.
  test.use({ viewport: { width: 3460, height: 400 } });

  test('the sheet renders values and NULL of every data type', async ({
    page,
    api,
    schema,
  }) => {
    await runSqlInSchema(
      schema,
      `CREATE TYPE "Level" AS ENUM ('low', 'high');
       CREATE TABLE "Everything" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Flag" boolean, "Choice" boolean, "Level" "Level", "Count" integer,
         "Price" mathesar_types.mathesar_money, "Day" date, "At" time,
         "Stamp" timestamp, "Span" interval, "Name" text,
         "Mail" mathesar_types.email, "Site" mathesar_types.uri, "Code" uuid,
         "Data" jsonb, "Tags" text[], "Owner" integer, "Host" inet,
         "List" mathesar_types.mathesar_json_array,
         "Map" mathesar_types.mathesar_json_object, "File" jsonb
       );
       INSERT INTO "Everything" ("Flag", "Choice", "Level", "Count", "Price",
         "Day", "At", "Stamp", "Span", "Name", "Mail", "Site", "Code", "Data",
         "Tags", "Host", "List", "Map")
       VALUES
         (true, true, 'low', 7, 2.5, '2024-03-15', '13:45', '2024-03-15 13:45',
          '00:01:30', 'Ada', 'ada@example.com', 'https://mathesar.org',
          '11111111-1111-1111-1111-111111111111', '{"a": 1}', '{x,y}',
          '10.0.0.1', '[1, 2]', '{"k": 1}'),
         (false, false, 'high', -1200, -3, '1999-12-31', '00:00',
          '1999-12-31 23:59:59', '2 days 03:00:00',
          'A text that is longer than its column', 'grace@example.org',
          'https://example.com/a/long/path', '22222222-2222-2222-2222-222222222222',
          '[true, null]', '{}', '::1', '[]', '{}'),
         (NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL,
          NULL, NULL, NULL, NULL, NULL, NULL, NULL);`,
    );
    const admin = await api.findUser(env.admin.username);
    const image = await uploadFile(
      page.request,
      path.join(__dirname, 'assets', 'flag.png'),
    );
    await runSql(
      schema.database.name,
      `UPDATE ${quoteIdentifier(schema.name)}."Everything"
       SET "Owner" = $1, "File" = $2 WHERE id = 1`,
      [admin?.id, JSON.stringify(image)],
    );
    const table = await api.getTable(schema, 'Everything');
    await api.setColumnMetadata(table, 'Choice', { bool_input: 'dropdown' });
    await api.makeUserColumn(table, 'Owner');
    await api.setColumnMetadata(table, 'File', { file_backend: 'default' });
    const tablePage = new TablePage(page);
    await tablePage.goto(table);
    await tablePage.inspectorToggle.click();
    await expect(tablePage.inspector.root).toBeHidden();
    await expect(tablePage.sheet.cell(0, 'Owner')).toHaveText('admin');
    const { thumbnail } = new FileField(tablePage.sheet.cell(0, 'File'));
    await expect(thumbnail).toHaveJSProperty('complete', true);
    await expect(thumbnail).not.toHaveJSProperty('naturalWidth', 0);
    await expectSettled(page);

    await expect(new ScreenshotAreas(page).tableSheet).toHaveScreenshot(
      'sheet-with-every-data-type.png',
    );
  });
});

test.describe('the table page', () => {
  let tablePage: TablePage;
  let sheetArea: Locator;

  test.beforeEach(async ({ page, library }) => {
    tablePage = new TablePage(page);
    sheetArea = new ScreenshotAreas(page).tableSheet;
    await tablePage.goto(library.books);
    // The first cell is selected once the table has loaded.
    await expect(tablePage.sheet.activeCell).toHaveCount(1);
  });

  test('a range of selected cells around the active cell', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.dragBetween(sheet.cell(1, 'Title'), sheet.cell(3, 'Genre'));
    await expect(sheet.selectedCells).toHaveCount(9);
    await expectSettled(page);

    await expect(sheetArea).toHaveScreenshot('sheet-with-selected-range.png');
  });

  test('a date cell in edit mode with its date picker', async ({ page }) => {
    await page.clock.setFixedTime(new Date('2026-01-15T10:00:00Z'));
    const { sheet } = tablePage;
    await sheet.cell(1, 'Published').click();
    await page.keyboard.press('Enter');
    await expect(new DateTimePicker(page).preset('Today')).toBeVisible();
    await expectSettled(page);

    await expect(sheetArea).toHaveScreenshot('sheet-with-date-editor.png');
  });

  test('the context menu of a cell with the Row submenu', async ({ page }) => {
    await tablePage.sheet.cell(1, 'Author').click({ button: 'right' });
    await menuItem(page, 'Row').hover();
    await expect(menuItem(page, 'Duplicate Record')).toBeVisible();
    await expectSettled(page);

    await expect(sheetArea).toHaveScreenshot('sheet-with-context-menu.png');
  });

  test('the confirmation before two records are deleted', async ({ page }) => {
    const { sheet } = tablePage;
    await sheet.dragBetween(sheet.rowHeader(1), sheet.rowHeader(2));
    await sheet.rowHeader(1).click({ button: 'right' });
    await menuItem(page, 'Delete 2 Records').click();
    const confirmation = new Modal(page, 'Delete 2 Records?');
    await confirmation.expectOpen();
    await expectSettled(page);

    await expect(windowOf(confirmation.root)).toHaveScreenshot(
      'delete-records-confirmation.png',
    );
  });

  test('the Table tab of the inspector', async ({ page }) => {
    await tablePage.inspector.expectOpenTab('Table');
    await expect(
      new TableRelationships(page).referencesFromThisTable,
    ).toHaveCount(1);
    await expectSettled(page);

    await expect(tablePage.inspector.root).toHaveScreenshot(
      'inspector-table-tab.png',
    );
  });

  test.describe('in a viewport that fits all sections of the Column tab', () => {
    test.use({ viewport: { width: 1440, height: 1700 } });

    test('the Column tab of the inspector for a number column', async ({
      page,
    }) => {
      await tablePage.sheet.columnHeader('Pages').click();
      await tablePage.inspector.tab('Column').click();
      await expect(tablePage.inspector.button('Delete Column')).toBeVisible();
      await expectSettled(page);

      await expect(tablePage.inspector.root).toHaveScreenshot(
        'inspector-column-tab.png',
      );
    });
  });

  test('the Record tab of the inspector', async ({ page }) => {
    await tablePage.sheet.rowHeader(1).click();
    await tablePage.inspector.expectOpenTab('Record');
    await expectSettled(page);

    await expect(tablePage.inspector.root).toHaveScreenshot(
      'inspector-record-tab.png',
    );
  });

  test('the Cell tab of the inspector for a linked record', async ({
    page,
  }) => {
    await tablePage.sheet.cell(1, 'Author').click();
    await tablePage.inspector.tab('Cell').click();
    await tablePage.inspector.expectOpenTab('Cell');
    await expectSettled(page);

    await expect(tablePage.inspector.root).toHaveScreenshot(
      'inspector-cell-tab.png',
    );
  });
});

test.describe('a narrow viewport', () => {
  test.use({ viewport: { width: 400, height: 800 } });

  test('the table page with a compact header and toolbar', async ({
    page,
    library,
  }) => {
    // The status bar has no button named "Refresh" at this width.
    await page.goto(tableUrl(library.books));
    await expect(new TablePage(page).sheet.activeCell).toHaveCount(1);
    await expect(
      new TableRelationships(page).referencesFromThisTable,
    ).toHaveCount(1);
    await expectSettled(page);

    await expect(page).toHaveScreenshot('table-page-narrow.png');
  });
});
