import {
  type Database,
  type Exploration,
  type Form,
  type Schema,
  type Table,
  type User,
  runSqlInSchema,
  uniqueName,
} from '../../support/api/mathesar';
import { quoteIdentifier } from '../../support/api/postgres';
import { test as base } from '../../support/fixtures';

/** The schema "Library" of `database` with two tables and a view. */
export interface Library {
  schema: Schema;
  /** Two records. */
  authors: Table;
  /** Three records. "Title" is unique and is the summary of a record. */
  books: Table;
  /** A view of the books with more than 400 pages. */
  longBooks: Table;
}

interface NavigationFixtures {
  library: Library;
  /** A saved exploration of the book titles. Its name starts with "Titles" and is unique on the server, as Mathesar requires. */
  titles: Exploration;
  /** The form "Book form" for the books. */
  bookForm: Form;
  /** A second schema "Shop" in `database`, with the table "Orders". */
  shop: Schema;
  /** A second database with nothing but the schema "public". */
  otherDatabase: Database;
  /** A standard user whose role can read the tables of `library`. */
  reader: User;
}

export const test = base.extend<NavigationFixtures>({
  library: async ({ api, database }, use) => {
    const schema = await api.createSchema(database, 'Library');
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Authors" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Name" text
       );
       INSERT INTO "Authors" ("Name") VALUES ('Frank Herbert'), ('Jane Austen');
       CREATE TABLE "Books" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Title" text UNIQUE,
         "Pages" integer
       );
       INSERT INTO "Books" ("Title", "Pages") VALUES
         ('Dune', 412), ('Emma', 320), ('Ulysses', 730);
       CREATE VIEW "Long Books" AS SELECT * FROM "Books" WHERE "Pages" > 400;`,
    );
    await use({
      schema,
      authors: await api.getTable(schema, 'Authors'),
      books: await api.getTable(schema, 'Books'),
      longBooks: await api.getTable(schema, 'Long Books'),
    });
  },

  titles: async ({ api, library }, use) => {
    await use(
      await api.defineExploration(library.books, {
        name: uniqueName('Titles'),
        columns: ['Title'],
      }),
    );
  },

  bookForm: async ({ api, library }, use) => {
    await use(
      await api.defineForm(library.books, { name: 'Book form', fields: [] }),
    );
  },

  shop: async ({ api, database }, use) => {
    const schema = await api.createSchema(database, 'Shop');
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Orders" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Customer" text
       );
       INSERT INTO "Orders" ("Customer") VALUES ('Ada');`,
    );
    await use(schema);
  },

  otherDatabase: async ({ api, pendingCleanups }, use) => {
    const database = await api.createDatabase();
    await use(database);
    pendingCleanups.push((admin) => admin.dropDatabase(database));
  },

  reader: async ({ collaborator, library }, use) => {
    const schema = quoteIdentifier(library.schema.name);
    const role = quoteIdentifier(collaborator.role.name);
    await runSqlInSchema(
      library.schema,
      `GRANT USAGE ON SCHEMA ${schema} TO ${role};
       GRANT SELECT ON ALL TABLES IN SCHEMA ${schema} TO ${role};`,
    );
    await use(collaborator.user);
  },
});

