/** "Books" with a foreign key to "Authors". "Authors" has three records, "Books" none. */
export interface Library {
  authors: Table;
  books: Table;
}

export interface Book {
  title: string;
  pages: number | null;
  price: number | null;
  inStock: boolean | null;
  published: string | null;
  /** The name of the author. */
  author: string | null;
  notes: string | null;
}

export interface Author {
  name: string;
  country: string | null;
}

interface FormsFixtures {
  library: Library;
  /** "Book intake": a form without a public link, with the fields that `bookFields` gives. */
  bookForm: Form;
  /** A page in a browser without a session, as the visitor of a public form has it. */
  visitor: Page;
  /** A stored role without privileges, for a test that makes another role a member of it. */
  groupRole: StoredRole;
}

export const AUTHOR_NAMES = [
  'Octavia Butler',
  'Stanislaw Lem',
  'Ursula Le Guin',
];

/** The labels of the fields that `bookFields` gives. */
export const BOOK_FIELD_LABELS = [
  'Title',
  'Pages',
  'Price',
  'In Stock',
  'Published',
  'Author',
  'Notes',
];

/**
 * A field for every column of "Books" that a form can fill. With a rule that
 * allows a new author, the author field gets a field for each column of "Authors".
 */
export function bookFields(
  library: Library,
  authorRule: ForeignKeyRule = 'must_pick',
): NewFormField[] {
  const authorFields =
    authorRule === 'must_pick'
      ? []
      : [{ column: 'Name' }, { column: 'Country' }];
  return BOOK_FIELD_LABELS.map((column) =>
    column === 'Author'
      ? {
          column,
          link: {
            table: library.authors,
            rule: authorRule,
            fields: authorFields,
          },
        }
      : { column },
  );
}

export function labelsOf(
  fields: FormFieldDefinition[] = [],
): (string | null)[] {
  return fields.map(({ label }) => label);
}

export function storedBooks(library: Library): Promise<Book[]> {
  return runSqlInSchema<Book>(
    library.books.schema,
    `SELECT "Title" AS title, "Pages" AS pages, "Price"::float AS price,
       "In Stock" AS "inStock", "Published"::text AS published,
       (SELECT "Name" FROM "Authors" WHERE id = "Author") AS author,
       "Notes" AS notes
     FROM "Books" ORDER BY id`,
  );
}

export function storedAuthors(library: Library): Promise<Author[]> {
  return runSqlInSchema<Author>(
    library.authors.schema,
    'SELECT "Name" AS name, "Country" AS country FROM "Authors" ORDER BY id',
  );
}

/** Lets a role read the tables of the library, which a form needs to load. */
export async function grantReading(
  library: Library,
  role: string,
): Promise<void> {
  const { schema } = library.books;
  const quotedSchema = quoteIdentifier(schema.name);
  const quotedRole = quoteIdentifier(role);
  await runSqlInSchema(
    schema,
    `GRANT USAGE ON SCHEMA ${quotedSchema} TO ${quotedRole};
     GRANT SELECT ON ALL TABLES IN SCHEMA ${quotedSchema} TO ${quotedRole};`,
  );
}

export const test = base.extend<FormsFixtures>({
  library: async ({ api, schema }, use) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Authors" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Name" text NOT NULL,
         "Country" text
       );
       INSERT INTO "Authors" ("Name", "Country") VALUES
         ('Ursula Le Guin', 'USA'), ('Stanislaw Lem', 'Poland'), ('Octavia Butler', 'USA');
       CREATE TABLE "Books" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Title" text NOT NULL,
         "Pages" integer,
         "Price" numeric,
         "In Stock" boolean,
         "Published" date,
         "Author" integer REFERENCES "Authors" (id),
         "Notes" text
       );`,
    );
    await use({
      authors: await api.getTable(schema, 'Authors'),
      books: await api.getTable(schema, 'Books'),
    });
  },

  bookForm: async ({ api, library }, use) => {
    await use(
      await api.defineForm(library.books, {
        name: 'Book intake',
        fields: bookFields(library),
      }),
    );
  },

  groupRole: async ({ api, database }, use) => {
    await use(await api.createStoredRole(database));
  },

  visitor: async ({ browser, allowedBrowserErrors }, use) => {
    // Without this, the new context would start with the admin's session.
    const context = await browser.newContext({
      storageState: { cookies: [], origins: [] },
    });
    const browserErrors: string[] = [];
    await guardBrowserContext(context, browserErrors);
    await use(await context.newPage());
    await context.close();
    expect(
      unexpectedErrors(browserErrors, allowedBrowserErrors),
      'the app threw or logged errors',
    ).toEqual([]);
  },
});

