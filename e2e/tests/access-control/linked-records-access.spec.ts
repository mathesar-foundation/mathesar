import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { RecordSelector } from '../../support/ui/components/record-selector';
import { RecordPage } from '../../support/ui/pages/record-page';
import { TablePage } from '../../support/ui/pages/table-page';
import { test as base, expect } from './fixtures';
import { grantOnSchema, grantOnTable } from './privileges';

interface Library {
  authors: Table;
  /** Each book links to an author through "Author", except "Ulysses". */
  books: Table;
}

const test = base.extend<{ library: Library }>({
  library: async ({ api, schema, collaborator }, use) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Authors" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Name" text
       );
       INSERT INTO "Authors" ("Name") VALUES ('Frank Herbert'), ('Jane Austen');
       CREATE TABLE "Books" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Title" text,
         "Author" integer REFERENCES "Authors" (id)
       );
       INSERT INTO "Books" ("Title", "Author") VALUES
         ('Dune', 1), ('Emma', 2), ('Ulysses', NULL);`,
    );
    await grantOnSchema(schema, collaborator.role.name, 'USAGE');
    await use({
      authors: await api.getTable(schema, 'Authors'),
      books: await api.getTable(schema, 'Books'),
    });
  },
});

test.describe('what a standard user may do with linked records', () => {
  test.describe('picking the author of a book', () => {
    /** Opens the record selector on the empty "Author" cell of "Ulysses". */
    async function openAuthorSelector(
      tablePage: TablePage,
      books: Table,
    ): Promise<RecordSelector> {
      await tablePage.goto(books);
      const { sheet } = tablePage;
      await sheet.cell(sheet.rowContaining('Ulysses'), 'Author').click();
      await tablePage.page.keyboard.press('Enter');
      return new RecordSelector(tablePage.page);
    }

    test('shows a warning in place of the authors without SELECT on them', async ({
      library: { books },
      signInAs,
      collaborator: { user, role },
    }) => {
      await grantOnTable(books, role.name, 'SELECT, UPDATE');
      const tablePage = new TablePage(await signInAs(user));
      const selector = await openAuthorSelector(tablePage, books);

      await expect(selector.warning).toHaveText(
        'Your role does not have the privileges to view this table.',
      );
      await expect(selector.searchInput('Name')).toHaveCount(0);
    });

    test('does not offer to create an author without INSERT on them', async ({
      library: { authors, books },
      signInAs,
      collaborator: { user, role },
    }) => {
      await grantOnTable(books, role.name, 'SELECT, UPDATE');
      await grantOnTable(authors, role.name, 'SELECT');
      const tablePage = new TablePage(await signInAs(user));
      const selector = await openAuthorSelector(tablePage, books);
      await selector.searchInput('Name').fill('James Joyce');

      await expect(selector.emptyNote).toHaveText('No matching records');
      await expect(selector.createRecordButton).toHaveCount(0);
    });

    test('creates the author from the search with INSERT on them', async ({
      schema,
      library: { authors, books },
      signInAs,
      collaborator: { user, role },
    }) => {
      await grantOnTable(books, role.name, 'SELECT, UPDATE');
      await grantOnTable(authors, role.name, 'SELECT, INSERT');
      const tablePage = new TablePage(await signInAs(user));
      const selector = await openAuthorSelector(tablePage, books);
      await selector.searchInput('Name').fill('James Joyce');
      await selector.createRecordButton.click();

      await selector.expectClosed();
      await expect
        .poll(() =>
          runSqlInSchema(
            schema,
            `SELECT "Name" FROM "Books" JOIN "Authors" ON "Authors".id = "Author"
             WHERE "Title" = 'Ulysses'`,
          ),
        )
        .toEqual([{ Name: 'James Joyce' }]);
    });
  });

  test('shows a warning in place of the books of an author without SELECT on them', async ({
    library: { authors },
    signInAs,
    collaborator: { user, role },
  }) => {
    await grantOnTable(authors, role.name, 'SELECT');
    const recordPage = new RecordPage(await signInAs(user));
    await recordPage.goto(authors, 1);

    await expect(recordPage.field('Name')).toHaveValue('Frank Herbert');
    await expect(recordPage.relatedRecords('Books').root).toContainText(
      'Your role does not have the privileges to view this table.',
    );
  });
});
