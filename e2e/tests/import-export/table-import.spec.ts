import type { Page } from '@playwright/test';

import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { holdRequests } from '../../support/held-requests';
import { pinsKnownBug } from '../../support/known-bugs';
import { chooseOption } from '../../support/ui/components/select';
import { Toasts } from '../../support/ui/components/toast';
import { TableImportModal } from '../../support/ui/pages/table-import-modal';
import { TablePage } from '../../support/ui/pages/table-page';
import { dataFile, expect, storedRecords, test } from './fixtures';

const BOOKS_SQL = `
  CREATE TABLE "Books" (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "Title" text,
    "Pages" integer,
    "Published" date
  );
  INSERT INTO "Books" ("Title", "Pages", "Published")
  VALUES ('Dune', 412, '1965-08-01');`;

/** What `Object.entries(undefined)` throws, as each browser words it. */
const ENTRIES_OF_UNDEFINED = {
  chromium: 'Cannot convert undefined or null to object',
  firefox: "can't convert undefined to object",
  webkit:
    'Object.entries requires that input parameter not be null or undefined',
};

async function openImport(page: Page, table: Table): Promise<TablePage> {
  const tablePage = new TablePage(page);
  await tablePage.goto(table);
  await tablePage.inspector.button('Import').click();
  return tablePage;
}

test.describe('import into a table', () => {
  let tablePage: TablePage;
  let importModal: TableImportModal;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(schema, BOOKS_SQL);
    tablePage = await openImport(page, await api.getTable(schema, 'Books'));
    importModal = new TableImportModal(page);
  });

  test('asks for a file first', async () => {
    await expect(importModal.dropZone).toBeVisible();
    await expect(importModal.importButton).toHaveCount(0);
  });

  test('matches the columns of the file to the table columns by name', async () => {
    await importModal.chooseFile(dataFile('more-books.csv'));

    await expect(importModal.file).toContainText('more-books.csv');
    await expect(importModal.file).toContainText('(72 Bytes)');
    await expect(importModal.firstRow).toHaveText('Column Names');
    await expect(importModal.csvColumns).toHaveText([
      'PUBLISHED',
      'title',
      'pages',
    ]);
    await expect(importModal.sampleValues).toHaveText([
      '1984-07-01',
      'Neuromancer',
      '271',
    ]);
    await expect(importModal.destinations).toHaveText([
      'Published',
      'Title',
      'Pages',
    ]);
    await expect(importModal.importButton).toBeEnabled();
  });

  test('offers the table columns that take values, and None', async () => {
    await importModal.chooseFile(dataFile('more-books.csv'));

    await expect(await importModal.destinationOptions(0)).toHaveText([
      'None',
      'Title',
      'Pages',
      'Published',
    ]);
  });

  test('a table column chosen for one file column is taken from the other', async () => {
    await importModal.chooseFile(dataFile('more-books.csv'));
    await importModal.mapColumn(1, 'Pages');

    await expect(importModal.destinations).toHaveText([
      'Published',
      'Pages',
      'None',
    ]);
  });

  test('Import needs at least one mapped column', async () => {
    await importModal.chooseFile(dataFile('one-book.csv'));
    await importModal.mapColumn(0, 'None');
    await importModal.mapColumn(1, 'None');
    await expect(importModal.importButton).toBeEnabled();

    await importModal.mapColumn(2, 'None');
    await expect(importModal.importButton).toBeDisabled();
  });

  test('imports the rows of the file and shows them in the table', async ({
    page,
    schema,
  }) => {
    await importModal.chooseFile(dataFile('more-books.csv'));
    await importModal.importButton.click();

    await new Toasts(page).expectMessage('Imported 2 rows.');
    await importModal.expectClosed();
    await expect(tablePage.sheet.recordRows).toHaveCount(3);
    await expect(tablePage.sheet.rowContaining('Kindred')).toBeVisible();
    expect(await storedRecords(schema, 'Books')).toEqual([
      { id: 1, Title: 'Dune', Pages: 412, Published: '1965-08-01' },
      { id: 2, Title: 'Neuromancer', Pages: 271, Published: '1984-07-01' },
      { id: 3, Title: 'Kindred', Pages: 264, Published: '1979-06-01' },
    ]);
  });

  test('leaves a table column empty that no file column maps to', async ({
    page,
    schema,
  }) => {
    await importModal.chooseFile(dataFile('one-book.csv'));
    await importModal.mapColumn(2, 'None');
    await importModal.importButton.click();

    await new Toasts(page).expectMessage('Imported one row.');
    expect(await storedRecords(schema, 'Books')).toContainEqual({
      id: 2,
      Title: 'Solaris',
      Pages: 204,
      Published: null,
    });
  });

  test('imports the first row as data when told so', async ({
    page,
    schema,
  }) => {
    await importModal.chooseFile(dataFile('books-without-header.csv'));
    await chooseOption(importModal.firstRow, 'Data to be Imported');

    await expect(importModal.csvColumns).toHaveText([
      'Column 1',
      'Column 2',
      'Column 3',
    ]);
    await expect(importModal.sampleValues).toHaveText([
      'Neuromancer',
      '271',
      '1984-07-01',
    ]);
    await expect(importModal.destinations).toHaveText([
      'Title',
      'Pages',
      'Published',
    ]);
    await importModal.importButton.click();
    await new Toasts(page).expectMessage('Imported 2 rows.');
    expect(await storedRecords(schema, 'Books')).toEqual([
      { id: 1, Title: 'Dune', Pages: 412, Published: '1965-08-01' },
      { id: 2, Title: 'Neuromancer', Pages: 271, Published: '1984-07-01' },
      { id: 3, Title: 'Kindred', Pages: 264, Published: '1979-06-01' },
    ]);
  });

  test('maps the file columns by position when no name matches', async () => {
    await importModal.chooseFile(dataFile('books-with-other-names.csv'));

    await expect(importModal.destinations).toHaveText([
      'Title',
      'Pages',
      'Published',
      'None',
    ]);
  });

  test(
    'maps a file column by position when the file has fewer columns, although its name matches in another case',
    pinsKnownBug('table-import-guess-ignores-case'),
    async () => {
      await importModal.chooseFile(dataFile('published-and-title.csv'));

      await expect(importModal.destinations).toHaveText(['Pages', 'Title']);
    },
  );

  test.fixme('maps a file column to the table column whose name matches in another case', async () => {
    await importModal.chooseFile(dataFile('published-and-title.csv'));

    await expect(importModal.destinations).toHaveText(['Published', 'Title']);
  });

  test('reports the error of the database under the Import button', async ({
    schema,
  }) => {
    await importModal.chooseFile(dataFile('books-with-bad-pages.csv'));
    await importModal.importButton.click();

    await expect(importModal.error).toContainText(
      'Unable to import data into existing table. invalid input syntax for type integer',
    );
    await importModal.expectOpen();
    expect(await storedRecords(schema, 'Books')).toHaveLength(1);
  });

  test('Import is disabled while the rows are imported', async ({ page }) => {
    const finishImport = await holdRequests(page, '**/bulk_insert/');
    await importModal.chooseFile(dataFile('one-book.csv'));
    await importModal.importButton.click();

    await expect(importModal.importButton).toBeDisabled();
    finishImport();
    await importModal.expectClosed();
  });

  test('removing the file returns to the drop zone', async () => {
    await importModal.chooseFile(dataFile('one-book.csv'));
    await importModal.removeFileButton.click();

    await expect(importModal.dropZone).toBeVisible();
    await expect(importModal.importButton).toHaveCount(0);
  });

  test('closes only with its close button and starts over when opened again', async ({
    page,
  }) => {
    await importModal.chooseFile(dataFile('one-book.csv'));
    await page.keyboard.press('Escape');
    await importModal.expectOpen();

    await importModal.close();
    await importModal.expectClosed();
    await tablePage.inspector.button('Import').click();
    await expect(importModal.dropZone).toBeVisible();
  });

  test.describe('with an empty file', () => {
    test.use({
      allowedBrowserErrors:
        /Cannot convert undefined or null|can't convert undefined|Object\.entries requires/,
    });

    test(
      'throws an uncaught error and keeps Import disabled',
      pinsKnownBug('table-import-empty-file'),
      async ({ page, browserName }) => {
        const uncaughtError = page.waitForEvent('pageerror');
        await importModal.chooseFile(dataFile('empty.csv'));

        expect((await uncaughtError).message).toContain(
          ENTRIES_OF_UNDEFINED[browserName],
        );
        await expect(importModal.file).toContainText('empty.csv');
        await expect(importModal.mapping).toHaveCount(0);
        await expect(importModal.importButton).toBeDisabled();
      },
    );
  });

  test.fixme('says that the file is empty', async () => {
    await importModal.chooseFile(dataFile('empty.csv'));

    await expect(importModal.parseError).toContainText(/empty/i);
    await expect(importModal.importButton).toBeDisabled();
  });
});

test.describe('import into a table with special columns', () => {
  test(
    'lists the file columns named like numbers first and fails to import them',
    pinsKnownBug('table-import-numeric-column-names'),
    async ({ page, api, schema }) => {
      await runSqlInSchema(
        schema,
        `CREATE TABLE "Sales" (
           id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
           "Region" text, "2023" integer, "2024" integer)`,
      );
      await openImport(page, await api.getTable(schema, 'Sales'));
      const importModal = new TableImportModal(page);
      await importModal.chooseFile(dataFile('sales.csv'));

      await expect(importModal.csvColumns).toHaveText([
        '2023',
        '2024',
        'Region',
      ]);
      await importModal.importButton.click();
      await expect(importModal.error).toContainText('Parsing mismatch');
      await importModal.expectOpen();
      expect(await storedRecords(schema, 'Sales')).toEqual([]);
    },
  );

  test.fixme('imports a file with columns named like numbers', async ({
    page,
    api,
    schema,
  }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Sales" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Region" text, "2023" integer, "2024" integer)`,
    );
    await openImport(page, await api.getTable(schema, 'Sales'));
    const importModal = new TableImportModal(page);
    await importModal.chooseFile(dataFile('sales.csv'));

    await expect(importModal.csvColumns).toHaveText(['Region', '2023', '2024']);
    await importModal.importButton.click();
    await new Toasts(page).expectMessage('Imported 2 rows.');
    expect(await storedRecords(schema, 'Sales')).toEqual([
      { id: 1, Region: 'North', 2023: 10, 2024: 12 },
      { id: 2, Region: 'South', 2023: 7, 2024: 9 },
    ]);
  });

  test('offers a generated column as a destination, and the import into it fails', async ({
    page,
    api,
    schema,
  }) => {
    await runSqlInSchema(
      schema,
      `${BOOKS_SQL}
       ALTER TABLE "Books" ADD COLUMN "Title Length" integer
         GENERATED ALWAYS AS (length("Title")) STORED;`,
    );
    await openImport(page, await api.getTable(schema, 'Books'));
    const importModal = new TableImportModal(page);
    await importModal.chooseFile(dataFile('one-book.csv'));
    await importModal.mapColumn(1, 'Title Length');
    await importModal.importButton.click();

    await expect(importModal.error).toContainText(
      'cannot insert a non-DEFAULT value into column',
    );
    await importModal.expectOpen();
    expect(await storedRecords(schema, 'Books')).toHaveLength(1);
  });
});
