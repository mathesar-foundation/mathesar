import { runSqlInSchema } from '../../support/api/mathesar';
import { FilterDropdown } from '../../support/ui/components/filter-dropdown';
import { menuItem } from '../../support/ui/components/menu';
import { Pagination } from '../../support/ui/components/pagination';
import { tooltip } from '../../support/ui/components/tooltip';
import { TableExportLink } from '../../support/ui/pages/table-export-link';
import { TablePage } from '../../support/ui/pages/table-page';
import { expect, test } from './fixtures';

const HEADER = 'id,Title,Pages,Published';
const DUNE = '1,Dune,412,1965-08-01 AD';
const EMMA = '2,Emma,474,1815-12-23 AD';
const ULYSSES = '3,Ulysses,730,1922-02-02 AD';
const KINDRED = '4,Kindred,264,1979-06-01 AD';

test.describe('export of a table', () => {
  let tablePage: TablePage;
  let exportLink: TableExportLink;

  test.beforeEach(async ({ page, api, schema }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Books" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Title" text, "Pages" integer, "Published" date);
       INSERT INTO "Books" ("Title", "Pages", "Published") VALUES
         ('Dune', 412, '1965-08-01'), ('Emma', 474, '1815-12-23'),
         ('Ulysses', 730, '1922-02-02'), ('Kindred', 264, '1979-06-01');`,
    );
    tablePage = new TablePage(page);
    exportLink = new TableExportLink(tablePage);
    await tablePage.goto(await api.getTable(schema, 'Books'));
  });

  test('downloads the records as a CSV file named after the table', async ({
    page,
  }) => {
    const pageUrl = page.url();
    const file = await exportLink.download();

    expect(file.name).toBe('Books.csv');
    expect(file.content.split('\r\n')).toEqual([
      HEADER,
      DUNE,
      EMMA,
      ULYSSES,
      KINDRED,
      '',
    ]);
    await expect(page).toHaveURL(pageUrl);
  });

  test('says that the export applies the filters and the sorting', async ({
    page,
  }) => {
    await exportLink.help.hover();

    await expect(tooltip(page)).toHaveText(
      'Export the Books table as a CSV file. Your current filters and sorting will be applied to the exported data.',
    );
  });

  test('applies the filter and the sorting of the table', async ({ page }) => {
    const filter = new FilterDropdown(tablePage);
    const condition = await filter.addFirstCondition('Pages');
    await condition.apply('is greater than', '400');
    await expect(tablePage.sheet.recordRows).toHaveCount(3);
    await tablePage.heading.click();
    await tablePage.sheet.columnHeader('Pages').click({ button: 'right' });
    await menuItem(page, 'Sort 9-0').click();
    await expect(tablePage.sheet.row(0)).toContainText('Ulysses');

    const file = await exportLink.download();
    expect(file.content.split('\r\n')).toEqual([
      HEADER,
      ULYSSES,
      EMMA,
      DUNE,
      '',
    ]);
  });

  test('sorts the records by the grouping column', async ({ page }) => {
    await tablePage.sheet.columnHeader('Title').click({ button: 'right' });
    await menuItem(page, 'Group by Column').click();
    await expect(tablePage.sheet.groupHeaders).toHaveCount(4);

    const file = await exportLink.download();
    expect(file.content.split('\r\n')).toEqual([
      HEADER,
      DUNE,
      EMMA,
      KINDRED,
      ULYSSES,
      '',
    ]);
  });

  test('includes the hidden columns', async ({ page }) => {
    await tablePage.sheet.columnHeader('Pages').click({ button: 'right' });
    await menuItem(page, 'Hide Column').click();
    await expect(tablePage.sheet.columnHeader('Pages')).toHaveCount(0);

    const file = await exportLink.download();
    expect(file.content.split('\r\n')[0]).toBe(HEADER);
  });
});

test('exports every record, not only the page that the table shows', async ({
  page,
  api,
  schema,
}) => {
  await runSqlInSchema(
    schema,
    `CREATE TABLE "Numbers" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "Number" integer);
     INSERT INTO "Numbers" ("Number") SELECT generate_series(1, 501);`,
  );
  const tablePage = new TablePage(page);
  await tablePage.goto(await api.getTable(schema, 'Numbers'));
  await expect(new Pagination(tablePage).currentPage).toHaveText('Page 1 of 2');

  const file = await new TableExportLink(tablePage).download();
  const lines = file.content.split('\r\n');
  expect(lines).toHaveLength(503);
  expect(lines.at(-2)).toBe('501,501');
});

test('quotes the values that need it and writes UTF-8', async ({
  page,
  api,
  schema,
}) => {
  await runSqlInSchema(
    schema,
    `CREATE TABLE "Notes" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "Text" text);
     INSERT INTO "Notes" ("Text") VALUES
       (NULL), (''), ('He said "hi", twice'), (E'two\\nlines'), ('Zoë in 東京');`,
  );
  const tablePage = new TablePage(page);
  await tablePage.goto(await api.getTable(schema, 'Notes'));

  const file = await new TableExportLink(tablePage).download();
  expect(file.content.split('\r\n')).toEqual([
    'id,Text',
    '1,',
    '2,',
    '3,"He said ""hi"", twice"',
    '4,"two\nlines"',
    '5,Zoë in 東京',
    '',
  ]);
});

test('writes each data type in its own format', async ({
  page,
  api,
  schema,
}) => {
  await runSqlInSchema(
    schema,
    `CREATE TABLE "Samples" (
       id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
       "Done" boolean, "Due" date, "At" time, "Stamp" timestamp,
       "Zoned" timestamptz, "Span" interval, "Ratio" numeric,
       "Price" mathesar_types.mathesar_money, "Meta" jsonb, "Tags" text[]);
     INSERT INTO "Samples"
       ("Done", "Due", "At", "Stamp", "Zoned", "Span", "Ratio", "Price", "Meta", "Tags")
     VALUES
       (true, '2024-03-15', '13:45:00', '2024-03-15 13:45:00',
        '2024-03-15 13:45:00+00', '1 day 02:30:00', 1234.5, 19.99,
        '{"a": 1}', '{x,y}'),
       (false, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL);`,
  );
  const tablePage = new TablePage(page);
  await tablePage.goto(await api.getTable(schema, 'Samples'));

  const file = await new TableExportLink(tablePage).download();
  expect(file.content.split('\r\n')).toEqual([
    'id,Done,Due,At,Stamp,Zoned,Span,Ratio,Price,Meta,Tags',
    '1,True,2024-03-15 AD,13:45:00.0,2024-03-15T13:45:00.0 AD,2024-03-15T13:45:00.0Z AD,P0Y0M1DT2H30M0S,1234.5,19.99,"{""a"": 1}","[\'x\', \'y\']"',
    '2,False,,,,,,,,,',
    '',
  ]);
});
