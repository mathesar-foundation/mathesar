import { runSqlInSchema } from '../../support/api/mathesar';
import { pinsKnownBug } from '../../support/known-bugs';
import { TablePage } from '../../support/ui/pages/table-page';
import { expect, test } from './books';

test.describe('the inspector follows the selection', () => {
  test('opens on the Table tab', async ({ tablePage: { inspector } }) => {
    await inspector.expectOpenTab('Table');
  });

  test('a click on a column header opens the Column tab for that column', async ({
    tablePage: { sheet, inspector },
  }) => {
    await sheet.columnHeader('Author').click();
    await inspector.expectOpenTab('Column');
    await expect(inspector.panel.getByRole('textbox').first()).toHaveValue(
      'Author',
    );

    await sheet.columnHeader('Pages').click();
    await expect(inspector.panel.getByRole('textbox').first()).toHaveValue(
      'Pages',
    );
  });

  test('a click on a row number opens the Record tab for that record', async ({
    books,
    tablePage: { sheet, inspector },
  }) => {
    await sheet.rowHeader(2).click();

    await inspector.expectOpenTab('Record');
    await expect(inspector.link('Open Record')).toHaveAttribute(
      'href',
      new RegExp(`/tables/${books.oid}/3$`),
    );
  });

  test('a click on a cell keeps the open tab, which follows the cell', async ({
    books,
    tablePage: { sheet, inspector },
  }) => {
    await sheet.rowHeader(2).click();
    await inspector.expectOpenTab('Record');
    await sheet.cell(1, 'Author').click();

    await inspector.expectOpenTab('Record');
    await expect(inspector.link('Open Record')).toHaveAttribute(
      'href',
      new RegExp(`/tables/${books.oid}/2$`),
    );
  });

  test('the Column tab shows the column of the active cell', async ({
    tablePage: { sheet, inspector },
  }) => {
    await inspector.tab('Column').click();
    await sheet.cell(1, 'Author').click();
    await expect(inspector.panel.getByRole('textbox').first()).toHaveValue(
      'Author',
    );

    await sheet.cell(1, 'Code').click();
    await expect(inspector.panel.getByRole('textbox').first()).toHaveValue(
      'Code',
    );
  });

  test('the Cell tab shows the value of the active cell as it changes', async ({
    page,
    tablePage: { sheet, inspector },
  }) => {
    await sheet.cell(2, 'Author').click();
    await inspector.tab('Cell').click();
    await expect(inspector.panel).toHaveText(/Content\s*James Joyce/);

    await sheet.cell(2, 'Author').click();
    await page.keyboard.press('ArrowRight');
    await expect(inspector.panel).toHaveText(/Content\s*730/);
  });

  test('several selected columns are counted on the Column tab', async ({
    tablePage: { sheet, inspector },
  }) => {
    await sheet.columnHeader('Author').click();
    await sheet.columnHeader('Pages').click({ modifiers: ['Shift'] });

    await expect(inspector.panel).toContainText('2 columns selected');
    await expect(
      inspector.button('Extract Columns Into a New Table'),
    ).toBeVisible();
  });

  test('several selected records are counted on the Record tab', async ({
    tablePage: { sheet, inspector },
  }) => {
    await sheet.dragBetween(sheet.rowHeader(0), sheet.rowHeader(2));

    await inspector.expectOpenTab('Record');
    await expect(inspector.panel).toContainText('3 records selected');
    await expect(inspector.button('Delete 3 Records')).toBeVisible();
  });

  test('the Record tab of a table without records asks to select cells, and offers the actions of a record added with New Record', async ({
    page,
    api,
    schema,
  }) => {
    await runSqlInSchema(
      schema,
      'CREATE TABLE "Empty" (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "Name" text)',
    );
    const tablePage = new TablePage(page);
    await tablePage.goto(await api.getTable(schema, 'Empty'));
    const { inspector } = tablePage;
    await inspector.tab('Record').click();

    await expect(inspector.panel).toHaveText(
      'Select one or more cells to view associated record properties.',
    );
    await tablePage.newRecordButton.click();
    await expect(inspector.button('Delete Record')).toBeVisible();
    await expect(inspector.panel).not.toContainText('Select one or more cells');
  });

  test(
    'with several records selected, Open Record links to a record named "undefined"',
    pinsKnownBug('inspector-open-record-with-several-records'),
    async ({ books, tablePage: { sheet, inspector } }) => {
      await sheet.dragBetween(sheet.rowHeader(0), sheet.rowHeader(2));

      await expect(inspector.link('Open Record')).toHaveAttribute(
        'href',
        new RegExp(`/tables/${books.oid}/undefined$`),
      );
    },
  );

  test.fixme('with several records selected, the actions for one record are not offered', async ({
    tablePage: { sheet, inspector },
  }) => {
    await sheet.dragBetween(sheet.rowHeader(0), sheet.rowHeader(2));

    await expect(inspector.link('Open Record')).toHaveCount(0);
    await expect(inspector.button('Quick View Record')).toHaveCount(0);
  });
});

test.describe('showing and hiding the inspector', () => {
  test('the Inspector button hides the panel and the choice survives a reload', async ({
    page,
    tablePage,
  }) => {
    await expect(tablePage.inspector.root).toBeVisible();
    await tablePage.inspectorToggle.click();
    await expect(tablePage.inspector.root).toHaveCount(0);

    await page.reload();
    await tablePage.expectLoaded();
    await expect(tablePage.inspector.root).toHaveCount(0);

    await tablePage.inspectorToggle.click();
    await expect(tablePage.inspector.root).toBeVisible();
  });
});
