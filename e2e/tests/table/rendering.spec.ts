import { runSqlInSchema } from '../../support/api/mathesar';
import { tooltip } from '../../support/ui/components/tooltip';
import { TablePage } from '../../support/ui/pages/table-page';
import { TableTab } from '../../support/ui/pages/table-tab';
import { expect, test } from './books';

test.describe('what the table page shows', () => {
  test('the table name, in the heading and in the page title', async ({
    page,
    tablePage,
  }) => {
    await expect(tablePage.heading).toHaveText('Books');
    await expect(page).toHaveTitle('Books | Mathesar');
  });

  test('the description of the table under the heading, also right after it changes in the inspector', async ({
    page,
    schema,
    books,
  }) => {
    await runSqlInSchema(schema, `COMMENT ON TABLE "Books" IS 'Novels'`);
    const tablePage = new TablePage(page);
    await tablePage.goto(books);
    await expect(tablePage.headingDescription()).toHaveText('Novels');

    const { description } = new TableTab(page, tablePage.inspector);
    await description.input.click();
    await description.input.fill('Long reads');
    await description.saveButton.click();

    await expect(tablePage.headingDescription()).toHaveText('Long reads');
  });

  test('one header per column, in table order, with the icon of its data type', async ({
    tablePage: { sheet },
  }) => {
    await expect(sheet.columnHeaders).toHaveText([
      'id',
      'Title',
      'Author',
      'Pages',
      'Code',
      'Notes',
    ]);
    await expect(sheet.columnTypeIcon('id')).toHaveAccessibleName('Number');
    await expect(sheet.columnTypeIcon('Title')).toHaveAccessibleName('Text');
    await expect(sheet.columnTypeIcon('Pages')).toHaveAccessibleName('Number');
  });

  test('one numbered row per record, with NULL marked as such', async ({
    tablePage,
  }) => {
    const { sheet } = tablePage;
    await expect(sheet.recordRows).toHaveCount(5);
    await expect(sheet.rowHeader(0)).toHaveText('1');
    await expect(sheet.rowHeader(4)).toHaveText('5');
    await expect(sheet.cell(4, 'Title')).toHaveText('Hamlet');
    await expect(sheet.cell(4, 'Author')).toHaveText('NULL');
    await expect(sheet.cell(2, 'Pages')).toHaveText('730');
    await expect(tablePage.recordCount).toHaveText('Showing 1–5 of 5');
    await expect(sheet.placeholderRow).toHaveCount(1);
  });

  test('a link in the primary key cell that opens the record in a modal', async ({
    page,
    books,
    tablePage,
  }) => {
    const link = tablePage.sheet.recordLink(1);
    await expect(link).toHaveAttribute(
      'href',
      `/db/${books.schema.database.id}/schemas/${books.schema.oid}/tables/${books.oid}/2`,
    );
    await link.click();

    await tablePage.recordModal.expectOpen();
    await expect(tablePage.recordModalField('Title')).toHaveValue('Emma');
    await expect(page).toHaveURL(new RegExp(`/tables/${books.oid}/$`));
  });
});

test.describe('special tables', () => {
  test('an empty table shows no records and the row that adds one', async ({
    page,
    api,
    schema,
  }) => {
    await runSqlInSchema(
      schema,
      'CREATE TABLE "Empty" (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "Name" text)',
    );
    const tablePage = new TablePage(page);
    await tablePage.goto(await api.getTable(schema, 'Empty'));

    await expect(tablePage.recordCount).toHaveText('No records found');
    await expect(tablePage.sheet.recordRows).toHaveCount(0);
    await expect(tablePage.sheet.placeholderRow).toHaveCount(1);
    await expect(tablePage.newRecordButton).toBeEnabled();
  });

  test('a table without a primary key is read-only', async ({
    page,
    api,
    schema,
  }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Log" ("Message" text, "Level" integer);
       INSERT INTO "Log" VALUES ('started', 1), ('stopped', 2);`,
    );
    const tablePage = new TablePage(page);
    await tablePage.goto(await api.getTable(schema, 'Log'));
    const { sheet } = tablePage;

    await expect(sheet.recordRows).toHaveCount(2);
    await expect(sheet.placeholderRow).toHaveCount(0);
    await expect(tablePage.newRecordButton).toHaveCount(0);
    await sheet.cell(0, 'Message').dblclick();
    await expect(sheet.editor).toHaveCount(0);
    await expect(tablePage.inspector.button('Import')).toBeDisabled();
  });

  test('a view is read-only and has no record tab', async ({
    page,
    api,
    schema,
    books,
  }) => {
    await runSqlInSchema(
      schema,
      `CREATE VIEW "Titles" AS SELECT id, "Title" FROM "${books.name}"`,
    );
    const tablePage = new TablePage(page);
    await tablePage.goto(await api.getTable(schema, 'Titles'));
    const { sheet, inspector } = tablePage;

    await expect(sheet.recordRows).toHaveCount(5);
    await expect(sheet.cell(0, 'Title')).toHaveText('Dune');
    await expect(sheet.placeholderRow).toHaveCount(0);
    await expect(tablePage.newRecordButton).toHaveCount(0);
    await expect(tablePage.toolbarButton('Extend')).toHaveCount(0);
    await expect(inspector.tab('View')).toBeVisible();
    await expect(inspector.tab('Record')).toHaveCount(0);
    await sheet.cell(0, 'Title').dblclick();
    await expect(sheet.editor).toHaveCount(0);
  });

  test('a view has the colour of views on the icon of its heading', async ({
    page,
    api,
    schema,
    books,
  }) => {
    await runSqlInSchema(
      schema,
      `CREATE VIEW "Titles" AS SELECT id, "Title" FROM "${books.name}"`,
    );
    const tablePage = new TablePage(page);
    await tablePage.goto(await api.getTable(schema, 'Titles'));

    await expect(tablePage.headingIcon()).toHaveCSS(
      'background-image',
      'linear-gradient(135deg, rgb(66, 115, 215), rgba(66, 115, 215, 0.8))',
    );
  });
});

test.describe('the warning icon in the header', () => {
  test('is not shown for a table with a primary key', async ({ tablePage }) => {
    await expect(tablePage.noPrimaryKeyWarning()).toHaveCount(0);
  });

  test('explains that a table without a primary key allows no row operations', async ({
    page,
    api,
    schema,
  }) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Log" ("Message" text, "Level" integer);
       INSERT INTO "Log" VALUES ('started', 1);`,
    );
    const tablePage = new TablePage(page);
    await tablePage.goto(await api.getTable(schema, 'Log'));
    await tablePage.noPrimaryKeyWarning().hover();

    await expect(tooltip(page)).toHaveText(
      'This table does not contain a Primary Key. Mathesar currently does not support row level operations for tables without Primary Keys.',
    );
  });

  test('explains that the definition of a view cannot be edited', async ({
    page,
    api,
    schema,
    books,
  }) => {
    await runSqlInSchema(
      schema,
      `CREATE VIEW "Titles" AS SELECT id, "Title" FROM "${books.name}"`,
    );
    const tablePage = new TablePage(page);
    await tablePage.goto(await api.getTable(schema, 'Titles'));
    await tablePage.noPrimaryKeyWarning().hover();

    await expect(tooltip(page)).toHaveText(
      'Mathesar currently does not support editing view definitions.',
    );
  });
});
