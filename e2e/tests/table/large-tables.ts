import { type Table, runSqlInSchema } from '../../support/api/mathesar';
import { test as base } from '../../support/fixtures';

interface LargeTableFixtures {
  /** 1200 records with "Label" values from "row 1" to "row 1200". More than a page holds. */
  longTable: Table;
  /** 30 text columns "C1" to "C30", wider than the viewport. Cell values look like "r2c7". */
  wideTable: Table;
}

export const test = base.extend<LargeTableFixtures>({
  longTable: async ({ api, schema }, use) => {
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Long" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         "Label" text,
         "Number" integer
       );
       INSERT INTO "Long" ("Label", "Number")
       SELECT 'row ' || n, n FROM generate_series(1, 1200) AS n;`,
    );
    await use(await api.getTable(schema, 'Long'));
  },

  wideTable: async ({ api, schema }, use) => {
    const columnNumbers = Array.from({ length: 30 }, (_, index) => index + 1);
    const columns = columnNumbers.map((n) => `"C${n}" text`).join(', ');
    const names = columnNumbers.map((n) => `"C${n}"`).join(', ');
    const values = columnNumbers.map((n) => `'r' || r || 'c${n}'`).join(', ');
    await runSqlInSchema(
      schema,
      `CREATE TABLE "Wide" (
         id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
         ${columns}
       );
       INSERT INTO "Wide" (${names})
       SELECT ${values} FROM generate_series(1, 40) AS r;`,
    );
    await use(await api.getTable(schema, 'Wide'));
  },
});

export { expect } from '../../support/fixtures';
